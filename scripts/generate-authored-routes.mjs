// Resolve the legacy registry once offline. Browser routes import just the
// winning family; the synchronous registry remains the independent reference.
import {readFile, writeFile} from 'node:fs/promises';
import {disposeMovementModel} from '../src/simulation/dispose-model.js';
const registryUrl = new URL('../src/simulation/registry.js', import.meta.url);
const registry = await readFile(registryUrl, 'utf8');
const catalog = JSON.parse(await readFile(new URL('../src/data/movements.json', import.meta.url))).movements;
const imports = new Map([...registry.matchAll(/import\s*\{\s*(\w+)\s*\}\s*from\s*'([^']+)';/g)].map(match => [match[1], match[2]]));
const names = [...registry.slice(registry.indexOf('export function createMovementModel')).matchAll(/(\w+)\(movement\)/g)].map(match => match[1]).filter(name => imports.has(name));
const families = [];
for (const name of names) {
  const path = imports.get(name);
  families.push({name, path, factory: (await import(new URL(path, registryUrl)))[name], ids: []});
}
for (const movement of catalog) {
  let found = false;
  for (const family of families) {
    const model = family.factory(movement);
    if (!model) continue;
    try {
      if (model.root.userData.fidelity !== 'authored') throw new Error(`Movement ${movement.id} is not authored`);
      family.ids.push(movement.id);
      found = true;
    } finally { disposeMovementModel(model); }
    break;
  }
  if (!found) throw new Error(`No factory for ${movement.id}`);
  if (movement.id % 25 === 0) {console.log(`Resolved ${movement.id}/507`); global.gc?.();}
}
const source = '// Generated by scripts/generate-authored-routes.mjs; registry.js is the reference.\n'
  + '// Keep literal imports so Vite can split each independent family.\nexport const authoredRoutes = [\n'
  + families.filter(family => family.ids.length).map(family => `  {ids: [${family.ids.join(', ')}], load: () => import('${family.path}').then(module => module.${family.name})},`).join('\n')
  + '\n];\n';
const destination = new URL('../src/simulation/authored-routes.js', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(destination, 'utf8') !== source) throw new Error('Authored routes are stale; regenerate them.');
} else await writeFile(destination, source);
console.log(`Resolved all 507 movements into ${families.filter(family => family.ids.length).length} families.`);
