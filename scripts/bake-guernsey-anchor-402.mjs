// Bake movement 402's wheel angle over one lever period from the finite
// anchor/wheel contact continuation (src/simulation/guernsey-anchor.js).
//   node scripts/bake-guernsey-anchor-402.mjs [--check]
import {readFileSync, writeFileSync} from 'node:fs';
import {bakeGuernsey402} from '../src/simulation/guernsey-anchor.js';
const bake = bakeGuernsey402();
const target = new URL('../src/simulation/baked/guernsey-anchor-402.js', import.meta.url);
const text = `// Generated by node scripts/bake-guernsey-anchor-402.mjs; do not hand edit.\nexport const guernseyAnchorBake = ${JSON.stringify(bake)};\n`;
if (process.argv.includes('--check')) { if (readFileSync(target, 'utf8') !== text) throw new Error('402 anchor bake differs; regenerate'); }
else writeFileSync(target, text);
console.log({samples: bake.angles.length, closureCorrection: bake.closureCorrection});
