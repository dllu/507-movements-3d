// Bakes movement 402's escape-wheel angle over one lever period: the lever
// (with anchor A) swings sinusoidally and the forward-urged wheel stops
// wherever its outline meets a pallet blade, is pushed back when a pallet
// goes deeper (recoil) and follows a withdrawing flank (impulse). See
// src/simulation/guernsey-anchor.js. Offline because the contact search takes
// about a second.
//   node scripts/bake-guernsey-anchor-402.mjs [--check]
import {readFileSync, writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {DESIGN, pitch, solveWheel} from '../src/simulation/guernsey-anchor.js';

const source = 'src/simulation/guernsey-anchor.js';
const solution = solveWheel();
if (solution.failed || solution.unresolved) throw new Error(`402 escapement does not advance one tooth per period (${solution.advance / pitch()} pitch)`);
const sha256 = createHash('sha256').update(readFileSync(new URL(`../${source}`, import.meta.url))).digest('hex');
// Actual wheel angle (radians, counter-clockwise positive) at phase i/steps.
const angles = Array.from(solution.angles, (u) => Number((DESIGN.sense * (solution.base + u)).toFixed(9)));
const states = Array.from(solution.states);
const bake = {period: DESIGN.period, steps: solution.stepsPerPeriod, advancePerPeriod: DESIGN.sense * pitch(),
  closure: Number(solution.closure.toExponential(3)), maxPush: Number(solution.maxPush.toExponential(3)),
  source: {file: source, sha256}, angles, states};
const target = new URL('../src/simulation/baked/guernsey-anchor-402.js', import.meta.url);
const text = '// Generated by node scripts/bake-guernsey-anchor-402.mjs; do not hand edit.\n'
  + '// One lever period of the escape wheel angle (phase i/steps); states: 0 free, 1 following a face, 2 pushed back, 3 resting.\n'
  + `export const guernseyAnchorBake = ${JSON.stringify(bake)};\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== text) { console.error('402 anchor bake is stale; regenerate'); process.exit(1); }
  console.log('up to date');
} else { writeFileSync(target, text); console.log({steps: bake.steps, closure: bake.closure, maxPush: bake.maxPush}); }
