import assert from 'node:assert/strict';
import {readFile, writeFile} from 'node:fs/promises';
import {createAuthoredMaintainingPowerMovement as chain} from '../src/simulation/authored-maintaining-power.js';
import {createAuthoredGoingBarrelMovement as barrel} from '../src/simulation/authored-going-barrels.js';
import {disposeMovementModel} from '../src/simulation/dispose-model.js';

// Exact finite-circle/ratchet intersections are useful offline, but need not
// be repeated at every browser frame. Refine each tooth period before export.
const paths={},tolerance=1e-6;
for(const [id,build] of [[320,chain],[321,barrel]]){
  const model=build({id,description:''});
  for(const follower of model.root.userData.blocks.finiteClicks){
    const pitch=2*Math.PI/follower.wheel.userData.ratchetProfile.teeth;
    const cache=new Map(),value=phase=>{
      if(!cache.has(phase))cache.set(phase,follower.angleAt(phase*pitch));
      return cache.get(phase);
    };
    const knots=[[0,value(0)]];
    function subdivide(a,b,depth=0){
      const ya=value(a),yb=value(b);
      const error=Math.max(...[.25,.5,.75].map(t=>Math.abs(value(a+(b-a)*t)-(ya+(yb-ya)*t))));
      assert.ok(depth<24,'nonconverging follower path');
      if(error>tolerance){const mid=(a+b)/2;subdivide(a,mid,depth+1);subdivide(mid,b,depth+1);}
      else knots.push([b,yb]);
    }
    for(let i=0;i<256;i++)subdivide(i/256,(i+1)/256);
    assert.ok(Math.abs(knots.at(-1)[1]-knots[0][1])<1e-12,'tooth-period seam');
    knots.at(-1)[1]=knots[0][1];
    const phaseScale=2**24;
    const compact=knots.map(([phase,angle])=>{
      assert.ok(Number.isInteger(phase*phaseScale),'phase precision needs more bits');
      return [phase*phaseScale,Number(angle.toFixed(9))];
    });
    paths[follower.bakeKey]={pitch,tolerance,phaseScale,signature:follower.bakeSignature,knots:compact};
    console.log(`${follower.bakeKey}: ${knots.length} keys, ${cache.size} exact samples`);
  }
  disposeMovementModel(model);
}
const output=new URL('../src/simulation/baked/maintaining-clock-clicks.js',import.meta.url);
const text=`// Generated by scripts/bake-maintaining-clock-clicks.mjs.\nexport default ${JSON.stringify(paths)};\n`;
if(process.argv.includes('--check'))assert.equal(await readFile(output,'utf8'),text,'regenerate clock click paths');
else await writeFile(output,text);
