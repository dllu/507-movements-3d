// Solves the 183/184 quadrant-catch transfer offline and writes the motion
// table used by authored-quadrant-catches.js.
import { writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { solveQuadrantCatchCycle } from '../src/simulation/quadrant-catch-finite-parts.js';

const started = Date.now();
const { samples, rows, noseR } = solveQuadrantCatchCycle({ samples: 720 });
const source = new URL('../src/simulation/quadrant-catch-finite-parts.js', import.meta.url);
const sha = createHash('sha256').update(readFileSync(source)).digest('hex');
const table = rows.map((r) => r.map((v) => Math.round(v * 1e4) / 1e4));
const text = `// Generated by scripts/bake-quadrant-catch.mjs from src/simulation/quadrant-catch-finite-parts.js. Do not edit.
// Columns: tappet top (plate-183 px, y down), upper handle angle, lower handle angle (degrees, clockwise on the page).
export const quadrantCatchMotion = ${JSON.stringify({ samples, noseR, sourceSha256: sha, rows: table })};
`;
writeFileSync(new URL('../src/simulation/baked/quadrant-catch-motion.js', import.meta.url), text);
console.log(JSON.stringify({ samples, rows: rows.length, seconds: (Date.now() - started) / 1000, sha }));
