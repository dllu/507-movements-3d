// Offline finite-polygon contact branch for movement 455. No fluid dynamics.
import fs from 'node:fs';
import {oldPumpVaneOutline} from '../src/simulation/old-pump-vane-geometry.js';
// Brown's hexagonal ring rotor is about half the casing radius; its leaf
// valves fold flat along the ring's facets.
const rotorRadius=1.16,casingRadius=2.35,valveLength=casingRadius-rotorRadius;
const {blade,lip}=oldPumpVaneOutline(rotorRadius,valveLength);
const outlines=[...blade,...lip].map(p=>p[0]);
// Brown's abutment is a square block filling the lower-right corner of the
// annulus: a horizontal top face and a vertical face beside the inlet, both
// running out to the 2.35-radius casing wall.
const corner=[.42,-1.40],clearance=.00015,step=Math.PI/3600;
// The block stops 0.002 short of the wall, where the vane's sealing lip
// runs, and is carried by the rear cover; contact is taken against its two
// straight faces.
const blockRadius=casingRadius-.002;
const topEnd=Math.atan2(corner[1],Math.sqrt(blockRadius**2-corner[1]**2)),sideEnd=Math.atan2(-Math.sqrt(blockRadius**2-corner[0]**2),corner[0]);
const block=[corner,...Array.from({length:97},(_,i)=>{const a=topEnd+(sideEnd-topEnd)*i/96;return[blockRadius*Math.cos(a),blockRadius*Math.sin(a)];}),corner];
const faces=[[block[1],corner],[corner,block[97]]];
const inside=(p,ring)=>{let c=false;for(let i=0,j=ring.length-2;i<ring.length-1;j=i++){const [xi,yi]=ring[i],[xj,yj]=ring[j];if((yi>p[1])!==(yj>p[1])&&p[0]<(xj-xi)*(p[1]-yi)/(yj-yi)+xi)c=!c;}return c;};
const closest=(p,u,v)=>{const x=v[0]-u[0],y=v[1]-u[1],t=Math.max(0,Math.min(1,((p[0]-u[0])*x+(p[1]-u[1])*y)/(x*x+y*y)));return[u[0]+t*x,u[1]+t*y];};
function contact(a,f){
  // World -> vane frame (hinge on the rotor vertex, vane direction a+f).
  const c=Math.cos(a+f),s=Math.sin(a+f),hx=rotorRadius*Math.cos(a),hy=rotorRadius*Math.sin(a);
  const toVane=([x,y])=>{const dx=x-hx,dy=y-hy;return[dx*c+dy*s,-dx*s+dy*c];};
  const vaneFaces=faces.map(([u,v])=>[toVane(u),toVane(v)]),vaneBlock=block.map(toVane);
  let distance=Infinity,point,normal;
  const consider=(q,b)=>{const d=Math.hypot(q[0]-b[0],q[1]-b[1]);if(d<distance){distance=d;point=q;normal=[(q[0]-b[0])/d,(q[1]-b[1])/d];}};
  for(const ring of outlines)for(let i=0;i<ring.length-1;i++){
    const u=ring[i],v=ring[i+1];
    // Vane vertices against block faces, block corner against vane edges.
    for(const [a0,a1] of vaneFaces)consider(u,closest(u,a0,a1));
    // Block face end points (corner and the two wall junctions) against vane edges.
    for(const k of [vaneBlock[0],vaneBlock[1],vaneBlock[97]])consider(closest(k,u,v),k);
  }
  let penetrating=false;
  for(const ring of outlines)for(const q of ring)if(inside(q,vaneBlock)){penetrating=true;break;}
  for(const k of vaneBlock)for(const ring of outlines)if(inside(k,ring)){penetrating=true;break;}
  const gap=penetrating?-distance:distance;
  return {gap,momentArm:point[0]*normal[1]-point[1]*normal[0]};
}
const values=[];let fold=0,maximum=0,peak=0;
for(let i=0;i<=2900;i++){
  const a=-i*step;
  while(contact(a,fold).gap<clearance&&fold<Math.PI)fold+=.002;
  while(fold>.002&&contact(a,fold-.002).gap>clearance)fold-=.002;
  let low=Math.max(0,fold-.002),high=fold;
  for(let n=0;n<30;n++){const mid=(low+high)/2;if(contact(a,mid).gap<clearance)low=mid;else high=mid;}
  fold=high;if(fold>maximum){maximum=fold;peak=i;}
  values.push(fold<1e-9?0:fold);
}
for(let i=peak;i<=3600;i++){
  const t=Math.max(0,Math.min(1,(i*step-145*Math.PI/180)/(33*Math.PI/180)));
  values[i]=maximum*(1-t*t*t*(10+t*(-15+6*t)));
}
let minimumMoment=Infinity,minimumGap=Infinity;
for(let i=0;i<=3600;i++){
  const c=contact(-i*step,values[i]);minimumGap=Math.min(minimumGap,c.gap);
  if(i<=peak&&values[i]>1e-8)minimumMoment=Math.min(minimumMoment,c.momentArm);
}
const record={block,corner,casingRadius,blockRadius,rotorRadius,valveLength,clearance,step,peakAngle:peak*step,maximumFold:maximum,minimumClosingMomentArm:minimumMoment,minimumSampleGap:minimumGap,fold:values.slice(0,peak+1).map(v=>Number(v.toFixed(9)))};
fs.writeFileSync(new URL('../src/simulation/old-pump-contact-profile.js',import.meta.url),`// Generated by scripts/generate-old-pump-contact.mjs; finite contact, prescribed return.\nexport default ${JSON.stringify(record)};\n`);
console.log({...record,fold:`${record.fold.length} samples`});
