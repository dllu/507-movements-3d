// Offline finite-polygon contact branch for movement 455. No fluid dynamics.
import fs from 'node:fs';
import {oldPumpVaneOutline} from '../src/simulation/old-pump-vane-geometry.js';
const {blade,lip}=oldPumpVaneOutline(.92,1.43);
const outlines=[...blade,...lip].map(p=>p[0]);
const center=[.99,-1.98*Math.sqrt(3)/2],radius=.65,clearance=.00015,step=Math.PI/3600;
function contact(a,f){
  const c=Math.cos(a+f),s=Math.sin(a+f),dx=center[0]-.92*Math.cos(a),dy=center[1]-.92*Math.sin(a),p=[dx*c+dy*s,-dx*s+dy*c];
  let distance=Infinity,point;
  for(const ring of outlines)for(let i=0;i<ring.length-1;i++){
    const u=ring[i],v=ring[i+1],x=v[0]-u[0],y=v[1]-u[1],t=Math.max(0,Math.min(1,((p[0]-u[0])*x+(p[1]-u[1])*y)/(x*x+y*y)));
    const q=[u[0]+t*x,u[1]+t*y],d=Math.hypot(p[0]-q[0],p[1]-q[1]);
    if(d<distance){distance=d;point=q;}
  }
  const normal=point.map((v,i)=>(v-p[i])/distance);
  return {gap:distance-radius,momentArm:point[0]*normal[1]-point[1]*normal[0]};
}
const values=[];let fold=0,maximum=0,peak=0;
for(let i=0;i<=2900;i++){
  const a=-i*step;
  while(contact(a,fold).gap<clearance&&fold<Math.PI)fold+=.002;
  while(fold>.002&&contact(a,fold-.002).gap>clearance)fold-=.002;
  let low=Math.max(0,fold-.002),high=fold;
  for(let n=0;n<30;n++){const mid=(low+high)/2;if(contact(a,mid).gap<clearance)low=mid;else high=mid;}
  fold=high;if(fold>maximum){maximum=fold;peak=i;}
  values.push(fold<1e-9?0:fold);
}
for(let i=peak;i<=3600;i++){
  const t=Math.max(0,Math.min(1,(i*step-145*Math.PI/180)/(33*Math.PI/180)));
  values[i]=maximum*(1-t*t*t*(10+t*(-15+6*t)));
}
let minimumMoment=Infinity,minimumGap=Infinity;
for(let i=0;i<=3600;i++){
  const c=contact(-i*step,values[i]);minimumGap=Math.min(minimumGap,c.gap);
  if(i<=peak&&values[i]>1e-8)minimumMoment=Math.min(minimumMoment,c.momentArm);
}
const record={center,radius,clearance,step,peakAngle:peak*step,maximumFold:maximum,minimumClosingMomentArm:minimumMoment,minimumSampleGap:minimumGap,fold:values.slice(0,peak+1).map(v=>Number(v.toFixed(9)))};
fs.writeFileSync(new URL('../src/simulation/old-pump-contact-profile.js',import.meta.url),`// Generated by scripts/generate-old-pump-contact.mjs; finite contact, prescribed return.\nexport default ${JSON.stringify(record)};\n`);
console.log({...record,fold:`${record.fold.length} samples`});
