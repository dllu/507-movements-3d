import fs from 'node:fs';
import {dualBandPawlDimensions as d,dualBandToothPitch as pitch,dualBandSeatPhase as seat,toe390Contact} from '../src/simulation/dual-band-pawl-contact.js';
// Solve the first contact met while lowering a finite toe from outside. The
// inner locking pocket is reached only after the crest passes; a slow enough
// prescribed return bridges that branch change without teleporting.
function envelope(q){let lo=1.8,hi=d.seatAngle;for(let i=0;i<45;i++){const mid=(lo+hi)/2;if(toe390Contact(mid,seat+q).gap<d.runningClearance)hi=mid;else lo=mid;}return(lo+hi)/2;}
const start=envelope(d.dropStart),N=4096,samples=[];
for(let i=0;i<=N;i++){
  const q=i*pitch/N,dropQ=q>pitch+d.dropStart?q-pitch:q;
  let angle=envelope(q);
  if(dropQ>=d.dropStart&&dropQ<=d.dropEnd){const u=(dropQ-d.dropStart)/(d.dropEnd-d.dropStart),smooth=u*u*u*(10+u*(-15+6*u));angle=Math.min(angle,start+(d.seatAngle-start)*smooth);}
  samples.push(Number(angle.toFixed(10)));
}
samples[N]=samples[0];
fs.writeFileSync(new URL('../src/simulation/dual-band-pawl-profile.js',import.meta.url),`// Generated by scripts/generate-dual-band-pawl-contact.mjs; radians, one tooth period.\nexport const dualBandPawlSamples = ${JSON.stringify(samples)};\n`);
console.log({seat,start,seatContact:toe390Contact(d.seatAngle,seat),samples:samples.length});
