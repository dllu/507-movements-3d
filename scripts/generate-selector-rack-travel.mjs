// Regenerates movement 084's playback profile from the free planar rack
// dynamics: the governor holds each selection for successive cam turns so the
// single cam walks the rack along its teeth, across the slots' travel, and back.
//   node scripts/generate-selector-rack-travel.mjs [--check-refinement]
import fs from 'node:fs';
import * as THREE from 'three';
import {makeSelectorRackFreeCandidate} from './lib/selector-rack-free-candidate.mjs';
import {makeSelectorRackDynamics, advanceSelectorRackStep, SELECTOR_RACK_SCHEDULE} from './lib/selector-rack-dynamics.mjs';
import {hashStudyFile} from './lib/study-report-io.mjs';

const refinement = process.argv.includes('--check-refinement');
const {duration} = SELECTOR_RACK_SCHEDULE, scale = 240;

function simulate(dt) {
  const model = makeSelectorRackFreeCandidate(), physics = makeSelectorRackDynamics(model);
  const vertexRadius = Math.max(...physics.contact.frame.flatMap(c => c.points.map(p => Math.hypot(...p))));
  let state = physics.initial, subdivisions = 0; const rows = [{time: 0, x: [...state.x]}];
  const advance = (h, depth = 0) => {
    const result = advanceSelectorRackStep(physics, state, h);
    const step = result.okay ? Math.hypot(result.state.x[0] - state.x[0], result.state.x[1] - state.x[1])
      + vertexRadius * Math.abs(result.state.x[2] - state.x[2]) : Infinity;
    if (!result.okay || step * scale > .25) {
      subdivisions++;
      if (depth > 14) throw Error(`084 dynamics failed at ${state.time}: ${result.reason}`);
      advance(h / 2, depth + 1); advance(h / 2, depth + 1); return;
    }
    state = result.state; rows.push({time: state.time, x: [...state.x]});
  };
  while (state.time < duration - 1e-12) advance(Math.min(dt, duration - state.time));
  return {model, physics, rows, vertexRadius, subdivisions};
}

const interpolate = (rows, time) => {
  let low = 0, high = rows.length - 1;
  while (high - low > 1) {const mid = (low + high) >> 1; if (rows[mid].time <= time) low = mid; else high = mid;}
  const a = rows[low], b = rows[high], f = b.time > a.time ? Math.max(0, Math.min(1, (time - a.time) / (b.time - a.time))) : 0;
  return a.x.map((v, i) => v + f * (b.x[i] - v));
};

// Keeps every frame vertex within `tolerance` pixels of the full solution.
function compress(rows, radius, tolerance = .001, maximumInterval = .02) {
  const keep = new Set([0, rows.length - 1]); let previous = 0;
  for (let i = 1; i < rows.length; i++) if (rows[i].time - rows[previous].time >= maximumInterval) {keep.add(i); previous = i;}
  const errorAt = (a, b, r) => {
    const f = (r.time - a.time) / (b.time - a.time), d = r.x.map((v, k) => v - a.x[k] - f * (b.x[k] - a.x[k]));
    return scale * (Math.hypot(d[0], d[1]) + radius * Math.abs(d[2]));
  };
  const start = [...keep].sort((a, b) => a - b), stack = start.slice(1).map((b, i) => [start[i], b]);
  while (stack.length) {
    const [a, b] = stack.pop(); let largest = 0, worst = -1;
    for (let i = a + 1; i < b; i++) {const e = errorAt(rows[a], rows[b], rows[i]); if (e > largest) {largest = e; worst = i;}}
    if (largest > tolerance) {keep.add(worst); stack.push([a, worst], [worst, b]);}
  }
  return [...keep].sort((a, b) => a - b).map(i => rows[i]);
}

const run = simulate(.0005), {model, physics, rows, vertexRadius} = run, u = model.root.userData;
const knots = compress(rows, vertexRadius);
const x0 = rows[0].x[0], travel = rows.map(r => (r.x[0] - x0) * scale);
const box = new THREE.Box3(), pose = new THREE.Box3();
for (let i = 0; i < knots.length; i += 4) {
  const {time, x} = knots[i], input = physics.input(time);
  model.setState({camAngle: input.camAngle, selectorY: input.selectorY, center: x.slice(0, 2), frameAngle: x[2]});
  for (const mesh of Object.values(u.parts)) box.union(pose.setFromObject(mesh, true));
}
const profile = {duration, period: SELECTOR_RACK_SCHEDULE.period, scale, neutral: physics.parameters.neutral,
  pulses: SELECTOR_RACK_SCHEDULE.pulses, damping: physics.parameters.damping,
  knots: knots.map(r => [r.time, ...r.x]),
  motionBounds: {min: box.min.toArray().map(v => v - .002), max: box.max.toArray().map(v => v + .002)}};
fs.writeFileSync('src/data/selector-rack-profile.js',
  '// Generated by scripts/generate-selector-rack-travel.mjs from the free planar rack contact dynamics.\nexport default '
  + JSON.stringify(profile) + ';\n');

const report = {movement: 84, generator: 'scripts/generate-selector-rack-travel.mjs', dt: .0005, states: rows.length,
  subdivisions: run.subdivisions, knots: knots.length, compressionPixels: .001, duration,
  travelPixels: [Math.min(...travel), Math.max(...travel)], slotLimitPixels: u.geometry.limits.rackX.map(v => v * scale),
  maximumTiltDegrees: Math.max(...rows.map(r => Math.abs(r.x[2]))) * 180 / Math.PI,
  restPositions: SELECTOR_RACK_SCHEDULE.pulses.flatMap(p => [p.rise[0], p.fall[1]]).map(t => +((interpolate(rows, t)[0] - x0) * scale).toFixed(2)),
  inputs: ['scripts/lib/selector-rack-dynamics.mjs', 'scripts/lib/selector-rack-candidate.mjs', 'scripts/lib/selector-rack-free-candidate.mjs',
    'scripts/lib/selector-rack-planar-contact.mjs', 'src/data/selector-rack-source.js'].map(file => ({file, sha256: hashStudyFile(file)}))};
if (refinement) {
  const coarse = simulate(.001); let worst = 0;
  for (const r of rows) {
    const x = interpolate(coarse.rows, r.time);
    worst = Math.max(worst, scale * (Math.hypot(x[0] - r.x[0], x[1] - r.x[1]) + vertexRadius * Math.abs(x[2] - r.x[2])));
  }
  report.refinement = {coarseDt: .001, maximumVertexDifferencePixels: worst};
}
fs.writeFileSync('artifacts/review/084-extended-travel.json', JSON.stringify(report, null, 2) + '\n');
console.log(report);
