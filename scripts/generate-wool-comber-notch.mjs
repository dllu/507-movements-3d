import fs from 'node:fs';
import * as THREE from 'three';
import {createAuthoredWoolComberMovement} from '../src/simulation/authored-wool-comber.js';
import {disposeObject3D} from '../src/simulation/dispose-model.js';

// Mill a convex relief envelope for the finite hook's actual entry/exit arcs.
// Generation stays offline; the browser consumes only this small closed profile.
const model = createAuthoredWoolComberMovement({id: 217});
try {
  const u = model.root.userData, g = u.geometry, m = u.motion;
  const clearance = .002, radius = g.catchHookRadius + clearance, cloud = [];
  for (const [start, end, rotation] of [
    [m.forwardEndPhase, m.liftRiseEndPhase, 0],
    [m.liftFallStartPhase, 1, m.netOutputAdvance],
  ]) for (let i = 0; i <= 128; i++) {
    const state = u.stateAtInputTravel((start + (end - start) * i / 128) * Math.PI * 2, 0, 0);
    const center = state.catchHookWorld.clone().sub(g.outputCenter)
      .rotateAround(new THREE.Vector2(), -state.outputAngle + rotation - g.notchPhaseAngle);
    for (let j = 0; j < 64; j++) {
      const angle = j * Math.PI / 32;
      cloud.push([center.x + radius * Math.cos(angle), center.y + radius * Math.sin(angle)]);
    }
  }
  cloud.sort((a, b) => a[0] - b[0] || a[1] - b[1]);
  const cross = (a, b, c) => (b[0] - a[0]) * (c[1] - a[1]) - (b[1] - a[1]) * (c[0] - a[0]);
  const half = points => {
    const result = [];
    for (const point of points) {
      while (result.length > 1 && cross(result.at(-2), result.at(-1), point) <= 0) result.pop();
      result.push(point);
    }
    return result.slice(0, -1);
  };
  const profile = [...half(cloud), ...half([...cloud].reverse())]
    .map(point => point.map(value => +value.toFixed(9)));
  fs.writeFileSync('src/data/wool-comber-notch.js',
    '// Generated by scripts/generate-wool-comber-notch.mjs; canonical notch points along +X.\n'
      + `export const woolComberNotch = ${JSON.stringify({clearance, hookRadius: g.catchHookRadius, profile})};\n`);
  console.log({vertices: profile.length, clearance});
} finally {disposeObject3D(model.root);}
