import fs from 'node:fs';
import * as THREE from 'three';
import {createWoolComberTransmission} from '../src/simulation/authored-wool-comber.js';
import {disposeObject3D} from '../src/simulation/dispose-model.js';

// Mill a convex relief envelope for the finite hook's actual entry/exit arcs.
// Generation stays offline; the browser consumes only this small closed profile.
const model = createWoolComberTransmission(217);
try {
  const u = model.root.userData, g = u.geometry, m = u.motion;
  const clearance = .002, radius = g.catchHookRadius + clearance, cloud = [];
  for (const [start, end, rotation] of [
    [m.forwardEndPhase, m.liftRiseEndPhase, 0],
    [m.liftFallStartPhase, 1, m.netOutputAdvance],
  ]) for (let i = 0; i <= 128; i++) {
    const state = u.stateAtInputTravel((start + (end - start) * i / 128) * Math.PI * 2, 0, 0);
    const center = state.catchHookWorld.clone().sub(g.outputCenter)
      .rotateAround(new THREE.Vector2(), -state.outputAngle + rotation - g.notchPhaseAngle);
    for (let j = 0; j < 128; j++) {
      const angle = j * Math.PI / 64;
      cloud.push([center.x + radius * Math.cos(angle), center.y + radius * Math.sin(angle)]);
    }
  }
  // 218's catch is a flat plate whose straight lug ends in this round tip,
  // so the root follows the tip and the lug nestles in it with only the
  // milling clearance (Brown's square root corner would leave a void).
  cloud.sort((a, b) => a[0] - b[0] || a[1] - b[1]);
  const cross = (a, b, c) => (b[0] - a[0]) * (c[1] - a[1]) - (b[1] - a[1]) * (c[0] - a[0]);
  const half = points => {
    const result = [];
    for (const point of points) {
      while (result.length > 1 && cross(result.at(-2), result.at(-1), point) <= 0) result.pop();
      result.push(point);
    }
    return result.slice(0, -1);
  };
  const hull = points => {
    points.sort((a, b) => a[0] - b[0] || a[1] - b[1]);
    return [...half(points), ...half([...points].reverse())].map(point => point.map(value => +value.toFixed(9)));
  };
  const profile = hull(cloud);
  // p99: 218's lug is square (flat end, small rounded corners), so its notch
  // is milled to that lug's own entry/exit envelope in 218's motion. 217
  // keeps the round-tip profile above.
  const model218 = createWoolComberTransmission(218);
  let square218;
  try {
    const u2 = model218.root.userData, g2 = u2.geometry, m2 = u2.motion, cloud2 = [];
    const outline = g2.catchLugOutline(0.2, clearance, 24, 48);
    for (const [start, end, rotation] of [
      [m2.forwardEndPhase, m2.liftRiseEndPhase, 0],
      [m2.liftFallStartPhase, 1, m2.netOutputAdvance],
    ]) for (let i = 0; i <= 128; i++) {
      const state = u2.stateAtInputTravel((start + (end - start) * i / 128) * Math.PI * 2, 0, 0);
      const turn = -state.outputAngle + rotation - g2.notchPhaseAngle;
      const pivot = state.catchPivotWorld.clone().sub(g2.outputCenter).rotateAround(new THREE.Vector2(), turn);
      for (const local of outline) {
        const point = local.clone().rotateAround(new THREE.Vector2(), state.catchAngle - state.outputAngle + rotation - g2.notchPhaseAngle).add(pivot);
        cloud2.push([point.x, point.y]);
      }
    }
    square218 = hull(cloud2);
  } finally {disposeObject3D(model218.root);}
  fs.writeFileSync('src/data/wool-comber-notch.js',
    '// Generated by scripts/generate-wool-comber-notch.mjs; canonical notch points along +X.\n'
      + `export const woolComberNotch = ${JSON.stringify({clearance, hookRadius: g.catchHookRadius, profile, square218})};\n`);
  console.log({vertices: profile.length, clearance});
} finally {disposeObject3D(model.root);}
