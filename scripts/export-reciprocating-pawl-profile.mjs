import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {makeReciprocatingPawlCandidate} from './lib/reciprocating-pawl-candidate.mjs';
import oldProfile from '../src/data/reciprocating-pawl-profile.js';
import {makeReciprocatingPawlMotion} from '../src/simulation/reciprocating-pawl-motion.js';
const trajectoryFile=process.env.TRAJECTORY||'artifacts/review/075-continuous-dynamics-refined.json',
  trajectory=JSON.parse(await readFile(trajectoryFile)),physicalPeriod=trajectory.parameters.period,
  slice=start=>trajectory.rows.filter(r=>r.time>=start-1e-8&&r.time<=start+physicalPeriod+1e-8)
    .map(r=>[Math.max(0,Math.min(physicalPeriod,r.time-start)),r.q,...r.x]),
  playback={period:physicalPeriod,first:slice(0),steady:slice(physicalPeriod)},
  sourceRod=[(790-627.2241913809899)/391.0844456767924,(641.9135290492636-732)/391.0844456767924],
  a=-oldProfile.parameters.sourceBarAngle,rodJoint=[sourceRod[0]*Math.cos(a)-sourceRod[1]*Math.sin(a),sourceRod[0]*Math.sin(a)+sourceRod[1]*Math.cos(a)],
  parameters={...oldProfile.parameters,period:4,sourcePhase:trajectory.parameters.sourcePhase,rodJoint,rodLength:1.16,overtravel:trajectory.parameters.overtravel},
  motionOverride=makeReciprocatingPawlMotion({...oldProfile,parameters,playback}),
  model=makeReciprocatingPawlCandidate({clockwiseTeeth:true,faceAngle:-.04,backBulge:.035,planarPawls:true,smoothPawls:true,motionOverride}),u=model.root.userData,parts=[];
if(trajectory.failures.length)throw Error('Cannot export a failed contact integration');
for(const key of ['slotAngle','slotLow','slotHigh'])delete u.geometry[key];
u.geometry.period=4;

for(const [name,mesh] of Object.entries(u.parts)){
  const g=mesh.geometry,shape=g.userData.plate?{kind:'plate',...g.userData.plate,
    polygons:g.parameters.shapes.map(s=>[s,...s.holes].map(r=>r.getPoints().map(p=>p.toArray())))}
    :{kind:'turned',...g.userData};
  parts.push({name,family:u.families[name],position:mesh.position.toArray(),color:mesh.material.color.toArray(),shape});
}
const provenance=[];
for(const file of ['scripts/lib/reciprocating-pawl-candidate.mjs','scripts/lib/reciprocating-pawl-contact-study.mjs',
  trajectoryFile,'scripts/lib/reciprocating-pawl-dynamics.mjs'])
  provenance.push({file,sha256:createHash('sha256').update(await readFile(file)).digest('hex')});
const profile={parameters:u.geometry,points:u.motion.points,mass:u.mass,parts,playback,physics:trajectory.parameters,provenance},
  literal=JSON.stringify(profile,(_,v)=>Object.is(v,-0)?'__NEGATIVE_ZERO__':v).replaceAll('"__NEGATIVE_ZERO__"','-0');
await writeFile('src/data/reciprocating-pawl-profile.js',
  '// Generated by scripts/export-reciprocating-pawl-profile.mjs. See artifacts/review/075-reconstruction-notes.md.\n'
  +'// The tooth count is a regularized reconstruction. Playback integrates finite unilateral contact, gravity and inertia with an opposing load.\n'
  +`export default ${literal};\n`);
console.log({parts:parts.length,bytes:literal.length});
