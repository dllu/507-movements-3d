import { writeFile } from 'node:fs/promises';
import { generateWormWheelProfile } from '../src/simulation/worm-wheel-profile.js';

const parameters = { teeth: 20, pitchRadius: 1.25, wormPitchRadius: 0.35,
  wormLength: 3.5 * Math.PI * 0.125, depth: 0.22, pressureAngle: Math.PI / 9 };
const start = Date.now();
const profile = generateWormWheelProfile(parameters, { phaseSteps: 1600, radialSteps: 80, clearance: 0.0004 });
await writeFile('artifacts/review/066-candidate-worm-profile.json', JSON.stringify({ parameters,
  seconds: (Date.now() - start) / 1000, profile }, null, 2) + '\n');
await writeFile('scripts/lib/gravity-jump-worm-profile.mjs',
  `// Isolated 066 candidate generated by scripts/generate-gravity-jump-worm-profile.mjs.\nexport default ${JSON.stringify({ ...profile, generatingPhases: undefined })};\n`);
console.log({ seconds: (Date.now() - start) / 1000, id: profile.id, samples: profile.radii.length,
  maximumSeamResidual: profile.maximumSeamResidual });
