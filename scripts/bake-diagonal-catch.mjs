const hash=file=>createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const asset='src/simulation/baked/assets/181.json.gz',keysModule='src/simulation/baked/diagonal-catch-keys.js';
// Compact synchronous copy of the baked motion for the offline registry route.
// Greedy piecewise-linear simplification keeps every dropped key within
// 3e-5 rad / 3e-5 units (about 1e-4 at the handle tips) of the linear interpolation between retained keys.
function writeKeys(bundle){
 const keys=bundle.motion,kept=[keys[0]],tolerance=3e-5;let start=0;
 for(let end=2;end<keys.length;end++){
  const a=keys[start],b=keys[end];let ok=true;
  for(let i=start+1;i<end&&ok;i++){const t=(keys[i][0]-a[0])/(b[0]-a[0]);
   for(let j=1;j<a.length;j++)if(Math.abs(a[j]+t*(b[j]-a[j])-keys[i][j])>tolerance){ok=false;break;}}
  if(!ok){kept.push(keys[end-1]);start=end-1;}
 }
 kept.push(keys.at(-1));
 const round=v=>Number(v.toPrecision(10));
 const data={period:bundle.period,loopStart:bundle.loopStart,loopEnd:bundle.loopEnd,names:bundle.names,turns:bundle.turns,
  bounds:bundle.bounds,focus:bundle.focus,assetSha256:hash(asset),motion:kept.map(k=>k.map(round))};
 fs.writeFileSync(keysModule,'// Generated by scripts/bake-diagonal-catch.mjs from '+asset+'. Do not edit.\n'
  +'export const diagonalCatchKeys='+JSON.stringify(data)+';\n');
 return kept.length;
}
if(process.argv.includes('--keys-from-asset')){
 console.log({keys:writeKeys(JSON.parse(gunzipSync(fs.readFileSync(asset)))) });process.exit(0);
}
const {createDiagonalCatchAssembly}=await import('../src/simulation/mujoco-diagonal-catch/assembly.js');
const report=JSON.parse(fs.readFileSync('docs/validation/181-projected-contact-motion.json'));
assert.ok(Object.values(report.controls).every(Boolean));
for(const source of report.sources)assert.equal(hash(source.file),source.sha256,source.file);
const input='/dev/shm/181-contact-motion.json',motion=JSON.parse(fs.readFileSync(input)),model=createDiagonalCatchAssembly();
try{
 const bounds=new THREE.Box3();
 for(let i=0;i<motion.keys.length;i+=10){model.update(motion.keys[i].slice(1));bounds.union(new THREE.Box3().setFromObject(model.root));}
 bounds.expandByScalar(.06);model.update(motion.keys[0].slice(1));
 model.root.traverse(o=>{o.userData={};});
 const sources=['scripts/bake-diagonal-catch.mjs','src/simulation/mujoco-diagonal-catch/assembly.js',
  'src/simulation/mujoco-diagonal-catch/update-solids.js','src/simulation/mujoco-diagonal-catch/catch-profile.js',
  'src/simulation/authored-diagonal-catches.js','src/simulation/finite-plate-geometry.js','docs/validation/181-projected-contact-motion.json']
  .map(file=>({file,sha256:hash(file)}));
 const bundle={version:1,movements:[181,182],object:model.root.toJSON(),names:motion.names,motion:motion.keys,
  period:motion.period,loopStart:0,loopEnd:motion.period,turns:[0,0,0,0],bounds:{min:bounds.min.toArray(),max:bounds.max.toArray()},
  focus:bounds.getCenter(new THREE.Vector3()).toArray(),inputHash:hash(input),sources};
 const bytes=gzipSync(JSON.stringify(bundle),{level:9});fs.writeFileSync(asset,bytes);const compactKeys=writeKeys(bundle);
 fs.writeFileSync('docs/validation/181-bake.json',JSON.stringify({...bundle,object:undefined,motion:undefined,keys:motion.keys.length,
  bytes:bytes.length,sha256:hash(asset),compactKeysModule:keysModule,compactKeys,compactKeysSha256:hash(keysModule),status:'baked-assembly-source-review-open'},null,2)+'\n');
 console.log({keys:motion.keys.length,compactKeys,bytes:bytes.length});
}finally{model.dispose();}
