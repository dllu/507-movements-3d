import {writeFile} from 'node:fs/promises';
import * as THREE from 'three';
import {openCrescentShuttleLaw} from '../src/simulation/open-crescent-shuttle-motion.js';
import {capsule,circle,poly,polygonClipping as clip} from '../src/simulation/finite-plate-geometry.js';
// p99: the slot is Brown's own arc as nearly as a working crank allows. His
// slot centreline is an arc of radius 93.4 px about (380.5, 239.9) px, i.e.
// concentric with his crank (380.1, 241.3), and spans 86-239 px from the
// rocker pivot (325.9, 406.0), a radial span of 153 px; his 94 px crank would
// need 188 px, so no closed slot of his shape fits his crank. The crank, pin
// and arc below minimise the largest of three misfits (slot centreline
// Hausdorff distance to his arc, crank centre and drawn pin, all 79.7 px per
// unit) with the rocker upright during a near-rest of at least 27% of the
// turn: 18.6 px, 18.6 px and 0.2 px. The p84 arc (sagitta 0.8 through the
// pin's nearest and farthest points at rest) missed his upper end by 48 px.
export const OPEN_CRESCENT_DESIGN={crankCenter:[.44636176,.06256826],crankRadius:.98526847,reference:142.69741535*Math.PI/180,arc:{center:[.56391245,2.08743206],radius:1.06759247}};
const law=openCrescentShuttleLaw({crankCenter:new THREE.Vector2(...OPEN_CRESCENT_DESIGN.crankCenter),rockerPivot:new THREE.Vector2(0,-2),crankRadius:OPEN_CRESCENT_DESIGN.crankRadius,reference:OPEN_CRESCENT_DESIGN.reference,period:6,arc:OPEN_CRESCENT_DESIGN.arc});
const points=Array.from({length:513},(_,i)=>law.pointAtRadius(law.low+(law.high-law.low)*i/512).toArray());
const stroke=r=>clip.union(...points.slice(1).map((p,i)=>capsule(points[i],p,r,12)));
const pocket=stroke(.1215),outer=stroke(.29),first=points[0],last=points.at(-1);
const lower=clip.union(capsule([0,0],first,.13,32),poly(circle([0,0],.22,64)));
// Brown draws the resting rocker upright: the top joint sits over the pivot
// in the rest pose (law phase 0), so it is set back by that rest angle here.
const lean=law.atPhase(0).angle,top=[3.75*Math.sin(lean),3.75*Math.cos(lean)];
const upper=clip.union(capsule(last,top,.13,32),poly(circle(top,.22,64)));
const bore=poly(circle([0,0],.144,64));
const data={points,pocket,body:clip.difference(outer,pocket),lower:clip.difference(lower,pocket,bore),upper:clip.difference(upper,pocket),parameters:{slotRadius:.1215,pinRadius:.12,low:law.low,high:law.high,restLean:lean,topJoint:top,...OPEN_CRESCENT_DESIGN}};
await writeFile(new URL('../src/simulation/baked/open-crescent-shuttle.js',import.meta.url),`// Generated by scripts/generate-open-crescent-shuttle.mjs.\nexport default ${JSON.stringify(data)};\n`);
console.log('Generated open crescent,',points.length,'centerline stations');
