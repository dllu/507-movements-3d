import {writeFile} from 'node:fs/promises';
import * as THREE from 'three';
import {openCrescentShuttleLaw} from '../src/simulation/open-crescent-shuttle-motion.js';
import {capsule,circle,poly,polygonClipping as clip} from '../src/simulation/finite-plate-geometry.js';
const law=openCrescentShuttleLaw({crankCenter:new THREE.Vector2(.78,.2),rockerPivot:new THREE.Vector2(0,-2),crankRadius:1.22,reference:Math.PI*150/180,period:6});
const points=Array.from({length:513},(_,i)=>law.pointAtRadius(law.low+(law.high-law.low)*i/512).toArray());
const stroke=r=>clip.union(...points.slice(1).map((p,i)=>capsule(points[i],p,r,12)));
const pocket=stroke(.1215),outer=stroke(.29),first=points[0],last=points.at(-1);
const lower=clip.union(capsule([0,0],first,.13,32),poly(circle([0,0],.22,64)));
const upper=clip.union(capsule(last,[0,3.75],.13,32),poly(circle([0,3.75],.22,64)));
const bore=poly(circle([0,0],.144,64));
const data={points,pocket,body:clip.difference(outer,pocket),lower:clip.difference(lower,pocket,bore),upper:clip.difference(upper,pocket),parameters:{slotRadius:.1215,pinRadius:.12,low:law.low,high:law.high}};
await writeFile(new URL('../src/simulation/baked/open-crescent-shuttle.js',import.meta.url),`// Generated by scripts/generate-open-crescent-shuttle.mjs.\nexport default ${JSON.stringify(data)};\n`);
console.log('Generated open crescent,',points.length,'centerline stations');
