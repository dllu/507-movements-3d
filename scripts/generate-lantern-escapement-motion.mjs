import assert from 'node:assert/strict';
import fs from 'node:fs';
import load from '@mujoco/mujoco';
import { createMujocoSimulation } from '../src/simulation/mujoco/simulation.js';
import { lanternXml297, initializeLantern297, driveLantern297 } from '../src/simulation/mujoco-lantern-escapement/model.js';
import { lanternContact297 as c, armState297, finiteContacts297, projectLanternPose297 } from '../src/simulation/lantern-pallet-contact.js';
const mujoco = await load(), sampleStep = .001, duration = 12;
function run(timestep, contact = true) {
  const sim = createMujocoSimulation(mujoco, { xml: lanternXml297({ timestep, contact }), initialize: initializeLantern297, beforeStep: driveLantern297 });
  const rows = [], stride = Math.round(sampleStep / timestep);
  let contacts = 0;
  for (let i = 0; i <= Math.round(duration / timestep); i++) {
    if (i % stride === 0) rows.push([i * timestep, sim.data.qpos[1], sim.data.qvel[1], sim.data.ncon]);
    contacts += sim.data.ncon; sim.step();
  }
  sim.dispose(); return { rows, contacts };
}
const fine = run(.0000625), coarse = run(.000125), disabled = run(.000125, false);
let angleAgreement = 0, rawMinimumGap = Infinity, projectionMaximum = 0;
for (let i = 4000; i < fine.rows.length; i++) {
  const row = fine.rows[i];
  assert.ok(row.every(Number.isFinite));
  angleAgreement = Math.max(angleAgreement, Math.abs(row[1] - coarse.rows[i][1]));
  rawMinimumGap = Math.min(rawMinimumGap, finiteContacts297(row[1], armState297(row[0]).angle)[0].gap);
}
assert.ok(angleAgreement < .008, `timestep angle disagreement ${angleAgreement}`);
const advances = [4, 8, 12].map((t, i, a) => i ? fine.rows[t * 1000][1] - fine.rows[a[i - 1] * 1000][1] : null).slice(1);
for (const advance of advances) assert.ok(Math.abs(advance - c.pitch) < 1e-6);
assert.equal(disabled.contacts, 0);
assert.ok(disabled.rows.at(-1)[1] - disabled.rows[0][1] > 10 * c.pitch, 'disabled wheel must run freely');
const angles = fine.rows.slice(8000, 12001).map(([time, angle]) => {
  const corrected = projectLanternPose297(angle, armState297(time).angle);
  projectionMaximum = Math.max(projectionMaximum, Math.abs(corrected - angle));
  return corrected - 2 * c.pitch;
});
assert.ok(projectionMaximum < .0015, `projection too large: ${projectionMaximum}`);
angles[4000] = angles[0] + c.pitch;
// Shape-preserving cubic slopes: no interpolated overshoot at an impact. Free
// flight inherits the simulated release speed instead of restarting at zero.
const slopes = angles.map((v, i) => {
  const before = i ? angles[i - 1] : angles[3999] - c.pitch;
  const after = i < 4000 ? angles[i + 1] : angles[1] + c.pitch;
  const left = (v - before) / sampleStep, right = (after - v) / sampleStep;
  return left * right <= 0 ? 0 : 2 * left * right / (left + right);
});
slopes[4000] = slopes[0];
const round = x => Number(x.toFixed(12));
const metadata = { engine: 'MuJoCo WASM', timestep: .0000625, controlTimestep: .000125, sampleStep, period: 4,
  angleAgreement: round(angleAgreement), rawMinimumGap: round(rawMinimumGap), projectionMaximum: round(projectionMaximum),
  steadyCycleAdvances: advances.map(round), disabledContactCount: disabled.contacts,
  disabledAdvance: round(disabled.rows.at(-1)[1] - disabled.rows[0][1]),
  method: 'Prescribed finite two-pallet oscillator, constant wheel torque, frictionless rigid planar contact; offline soft-overlap projection and monotone cubic playback.' };
const text = `// Generated by scripts/generate-lantern-escapement-motion.mjs; do not edit.\nexport const lanternMotion297 = ${JSON.stringify({ metadata, angles: angles.map(round), slopes: slopes.map(round) })};\n`;
const output = new URL('../src/simulation/baked/lantern-escapement-motion.js', import.meta.url);
if (process.argv.includes('--check')) assert.equal(fs.readFileSync(output, 'utf8'), text, '297 bake differs');
else fs.writeFileSync(output, text);
console.log(JSON.stringify(metadata, null, 2));
