import fs from 'node:fs';
import * as THREE from 'three';
import { makeCrownRatchetGeometry, capstanPawlLeadAngle, capstanPawlDimensions as g } from '../src/simulation/capstan-pawl-contact.js';
import { solidSurface } from '../tests/helpers/solid-surface.mjs';

const surface = solidSurface(makeCrownRatchetGeometry({ ...g, phaseOffset: capstanPawlLeadAngle }));
const pitch = 2*Math.PI/g.toothCount, count = 2560, clearance = 0.00012;
const center = (phase, angle) => {
  const radius = g.pivotRadius+g.length*Math.cos(angle);
  return new THREE.Vector3(radius*Math.cos(phase*pitch)-g.tipLead*Math.sin(phase*pitch),g.pivotHeight+g.length*Math.sin(angle),radius*Math.sin(phase*pitch)+g.tipLead*Math.cos(phase*pitch));
};
const contactPitch = phase => {
  let high=0,low=-0.025;
  while (surface.signedDistance(center(phase,low)) > g.tipRadius+clearance && low > -1.3) { high=low; low-=0.025; }
  if (low < -1.3) throw new Error('Missing crown contact');
  for (let i=0;i<28;i++) {
    const middle=(low+high)/2;
    if (surface.signedDistance(center(phase,middle)) > g.tipRadius+clearance) high=middle; else low=middle;
  }
  return high;
};
const releaseEnd=0.40, startHeight=g.highHeight+g.tipRadius+clearance;
const landingHeight=center(releaseEnd,contactPitch(releaseEnd)).y;
const samples=[];
for (let i=0;i<=count;i++) {
  const phase=i/count,contact=contactPitch(phase),u=Math.min(phase/releaseEnd,1),smooth=u*u*u*(10+u*(-15+6*u));
  const flightHeight=startHeight+(landingHeight-startHeight)*smooth;
  const flight=phase < releaseEnd ? Math.asin((flightHeight-g.pivotHeight)/g.length) : -Infinity;
  samples.push([+Math.max(contact,flight).toFixed(8),+contact.toFixed(8)]);
}
// Enforce exact periodic endpoint after the numerical surface queries.
samples[count]=samples[0].slice();
const output=`// Generated by scripts/generate-capstan-pawl-contact.mjs. Finite geometric\n// contact and prescribed crest release; not a dynamic gravity simulation.\nexport const capstanPawlSamples = ${JSON.stringify(samples)};\n`;
fs.writeFileSync(new URL('../src/simulation/capstan-pawl-profile.js',import.meta.url),output);
console.log({samples:samples.length,landingHeight,clearance});
