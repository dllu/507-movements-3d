import fs from 'node:fs';
import {makeWormSaddleProfile} from '../src/simulation/mujoco-worm-saddle/profile.js';
import {generateSaddleWheel} from '../src/simulation/mujoco-worm-saddle/hob.js';
const f=makeWormSaddleProfile(),options=JSON.parse(process.env.HOB_OPTIONS??'{"angularSteps":192,"axialSteps":32,"phaseSteps":1280,"radialSteps":128}'),start=performance.now();
const result=generateSaddleWheel(f,options),file=(process.env.PROBE_PREFIX??'/dev/shm/104-hob')+'.json';
fs.writeFileSync(file,JSON.stringify(result)+'\n',{flag:'wx'});
if(process.env.WRITE_MODULE){
  const {phases,...cut}=result;
  fs.writeFileSync(process.env.WRITE_MODULE,'// Generated by scripts/generate-worm-saddle-profile.mjs; one periodic hobbed tooth.\nexport const saddleWheelCut = '+JSON.stringify(cut)+';\n',{flag:'wx'});
}
console.log({file,seconds:(performance.now()-start)/1000,seamError:result.seamError,minimum:Math.min(...result.radii),maximum:Math.max(...result.radii),samples:result.radii.length});
