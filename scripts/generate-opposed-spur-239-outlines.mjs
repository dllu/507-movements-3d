// Offline finite envelope cutter; run with node scripts/generate-opposed-spur-239-outlines.mjs.
import { writeFile } from 'node:fs/promises';
import { createAuthoredGearMovement } from '../src/simulation/authored-gears.js';
import { poly, circle, capsule, polygonClipping } from '../src/simulation/finite-plate-geometry.js';
const model = createAuthoredGearMovement({id:239}), d = model.root.userData, g = d.geometry;
const sampleCount = 128, stopOutlines = {};
const clearance = 0.00012;
const raw = g.workingProfile.outline.filter((p, i, a) => !i || p.distanceTo(a[i - 1]) > 1e-10);
if (raw[0].distanceTo(raw.at(-1)) < 1e-10) raw.pop();
const cutterOutline = raw.map((p, i) => {
  const a = p.clone().sub(raw[(i + raw.length - 1) % raw.length]).normalize();
  const b = raw[(i + 1) % raw.length].clone().sub(p).normalize();
  const n1 = {x:a.y,y:-a.x}, n2 = {x:b.y,y:-b.x}, scale = clearance / (1 + n1.x*n2.x + n1.y*n2.y);
  return {x:p.x + (n1.x+n2.x)*scale, y:p.y + (n1.y+n2.y)*scale};
});
const rotate = (p, a) => [p.x * Math.cos(a) - p.y * Math.sin(a), p.x * Math.sin(a) + p.y * Math.cos(a)];
for (const side of ['left', 'right']) {
  const pivot = g[`${side}Pivot`];
  let outline = poly(d.workingParts239.sourceOutlines[side]);
  if (side === 'left') outline = polygonClipping.union(outline, poly(circle([0, 0], 0.30, 96)), capsule([0, 0], [0.40, 0.35], 0.14, 32));
  // The gear is the cutter, not a removed working part. Both endpoints are
  // included, so their resisting flank envelopes remain in the stop pockets.
  for (let i = 0; i <= sampleCount; i++) {
    const angle = g.gearMountPhase + g.clockwiseLimit * i / sampleCount;
    const cutter = poly(cutterOutline.map(p => {
      const q = rotate(p, angle); return [q[0] - pivot.x, q[1] - pivot.y];
    }));
    outline = polygonClipping.difference(outline, cutter);
  }
  // Restore a finite load land on the exact limiting flank, independently
  // checked against every intermediate pose. Relief elsewhere is running gap.
  const metric = d.stopMetricsAtWheelAngle(side, side === 'left' ? g.clockwiseLimit : 0);
  const q = metric.nose.clone().sub(pivot), t = metric.segment.outer.clone().sub(metric.segment.root).normalize();
  const n = side === 'left' ? {x:t.y,y:-t.x} : {x:-t.y,y:t.x};
  const land = poly([[-0.02,0],[0.02,0],[0.02,0.08],[-0.02,0.08]].map(([u,v]) => [q.x+t.x*u+n.x*v,q.y+t.y*u+n.y*v]));
  outline = polygonClipping.union(outline, land);
  stopOutlines[side] = outline;
  console.log(side, outline.length, outline.map(p => p.map(r => r.length)));
}
const destination = new URL('../src/simulation/baked/opposed-spur-239-outlines.js', import.meta.url);
await writeFile(destination, `// Generated by scripts/generate-opposed-spur-239-outlines.mjs; ${sampleCount + 1} cutter poses.\nexport const stopOutlines239 = ${JSON.stringify(stopOutlines)};\n`);
