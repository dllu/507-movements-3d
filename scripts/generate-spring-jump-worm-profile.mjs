import { writeFile } from 'node:fs/promises';
import { refinedWormProfile } from './lib/refined-worm-profile.mjs';

const parameters = { teeth: 24, pitchRadius: 1.375 / (1 + 2 / 24), wormPitchRadius: 0.33,
  wormLength: 1.6, depth: 0.22, pressureAngle: Math.PI / 9 };
const start = Date.now(), profile = refinedWormProfile(parameters, { phaseSteps: 1600, radialSteps: 80, clearance: 0.0004 });
await writeFile('artifacts/review/064-refined-worm-profile.json', JSON.stringify({ parameters, seconds: (Date.now() - start) / 1000, profile }, null, 2) + '\n');
await writeFile('src/data/spring-jump-worm-profile.js', `// Generated by scripts/generate-spring-jump-worm-profile.mjs.\nexport default ${JSON.stringify({ ...profile, generatingPhases: undefined })};\n`);
console.log({ seconds: (Date.now() - start) / 1000, id: profile.id, samples: profile.radii.length, maximumSeamResidual: profile.maximumSeamResidual });
