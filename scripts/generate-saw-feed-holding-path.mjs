// Deterministic, bounded offline click envelope and continuous prescribed drop.
// Run from the repository root with Node 18+; requires existing npm dependencies.
import * as THREE from 'three';
import { readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { createAuthoredSawFeedMovement } from '../src/simulation/authored-saw-feeds.js';
import { nearestSawFeedContact } from '../src/simulation/saw-feed-working-parts.js';
const model=createAuthoredSawFeedMovement({id:284}),d=model.root.userData,g=d.geometry;
const pivot=d.blocks.holdingPawl.position;
const contact=g.workingFlank.point.clone().addScaledVector(g.workingFlank.normal,.0552)
  .rotateAround(new THREE.Vector2(),g.ratchetMountPhase+13*g.ratchetToothPitch);
const length=contact.distanceTo(new THREE.Vector2(pivot.x,pivot.y));
const base=Math.atan2(contact.y-pivot.y,contact.x-pivot.x),count=512,clearance=.0006;
const envelope=[];
for(let i=0;i<=count;i++){
  const wheel=-g.ratchetToothPitch*i/count;
  const gap=a=>nearestSawFeedContact(new THREE.Vector2(pivot.x+length*Math.cos(a),pivot.y+length*Math.sin(a)),wheel,d.workingParts.outline).distance-.055;
  let lo=base-.9,hi;
  for(let j=1;j<=120;j++){const a=base-.9+j*.01;if(gap(a)<clearance){hi=a;lo=a-.01;break;}}
  if(hi===undefined)throw new Error(`No holding-toe contact at sample ${i}`);
  for(let j=0;j<40;j++){const mid=(lo+hi)/2;if(gap(mid)>clearance)lo=mid;else hi=mid;}
  envelope.push((lo+hi)/2);
}
// Greatest periodic Lipschitz minorant: a more negative angle lifts away from
// the wheel. This anticipates a crest and bounds the drop rate, avoiding the
// envelope's instantaneous angular jump. It is not a spring/gravity solution.
const slope=4;
const angles=envelope.map((value,i)=>Math.min(...envelope.map((q,j)=>q+slope*Math.min(Math.abs(i-j),count-Math.abs(i-j))/count))-.00005);
angles[count]=angles[0];
let minimum=Infinity;
for(let i=0;i<=8192;i++){
  const phase=i/8192,x=phase*count,index=Math.min(count-1,Math.floor(x)),f=x-index;
  const a=angles[index]*(1-f)+angles[index+1]*f;
  minimum=Math.min(minimum,nearestSawFeedContact(new THREE.Vector2(pivot.x+length*Math.cos(a),pivot.y+length*Math.sin(a)),-phase*g.ratchetToothPitch,d.workingParts.outline).distance-.055);
}
if(minimum<0)throw new Error(`Interpolation penetrates by ${minimum}`);
const data={length,radius:.055,slopeLimit:slope,clearance,minimumValidatedGap:minimum,angles};
const target=new URL('../src/simulation/baked/saw-feed-holding-path.js',import.meta.url);
const output=`// Generated by scripts/generate-saw-feed-holding-path.mjs.\nexport const sawFeedHoldingPath=${JSON.stringify(data)};\n`;
if(process.argv.includes('--check'))assert.equal(await readFile(target,'utf8'),output,'Holding-path data is stale');
else await writeFile(target,output);
console.log({samples:angles.length,minimumValidatedGap:minimum,length,maximumStep:Math.max(...angles.slice(1).map((v,i)=>Math.abs(v-angles[i])))});
