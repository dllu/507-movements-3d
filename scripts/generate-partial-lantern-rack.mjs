// Offline circle-cutter envelopes for Brown's partial (four of ten) lantern.
// Run with Node 18+ and the project's npm dependencies. The official
// triangular frame law is retained, including its impulsive reversal.
import {readFile,writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
import {createAuthoredGearMovement as create} from '../src/simulation/authored-gears.js';
const d=create({id:199}).root.userData,g=d.geometry;
const poses=4096,rows=384,clearance=.00035,blankExtension=.08;
const all=[];
for(let i=0;i<=poses;i++){
  const s=d.stateAtInputTravel(i*2*Math.PI/poses);
  for(const p of s.lanternPinCenters)all.push([p.x-s.frameTranslation.x,p.y]);
}
const simplify=(points,tolerance)=>{
  if(points.length<3)return points;
  const a=points[0],b=points.at(-1),dx=b[0]-a[0],dy=b[1]-a[1],den=dx*dx+dy*dy;
  let max=0,index=0;
  for(let i=1;i<points.length-1;i++){const p=points[i],u=Math.max(0,Math.min(1,((p[0]-a[0])*dx+(p[1]-a[1])*dy)/den));const distance=Math.hypot(p[0]-a[0]-u*dx,p[1]-a[1]-u*dy);if(distance>max){max=distance;index=i;}}
  if(max<=tolerance)return[a,b];
  return [...simplify(points.slice(0,index+1),tolerance).slice(0,-1),...simplify(points.slice(index),tolerance)];
};
const result=[];
for(const [side,profiles] of [[1,g.topRackProfilesInMotionOrder],[-1,g.bottomRackProfilesInMotionOrder]])for(let index=0;index<profiles.length;index++){
  const p=profiles[index],tip=Math.abs(p[1].y)-blankExtension,root=Math.abs(p[0].y)+.002;
  const xmin=Math.min(p[0].x-.015,p[1].x-blankExtension),xmax=Math.max(p[3].x+.015,p[2].x+blankExtension);
  const radius=g.lanternPinRadius+clearance;
  const cutters=all.map(([x,y])=>[x,side*y]).filter(([x,y])=>x>xmin-radius&&x<xmax+radius&&y>tip-radius&&y<root+radius);
  const left=[],right=[];let started=false;
  for(let row=0;row<=rows;row++){
    const y=tip+(root-tip)*row/rows,u=(y-tip)/(root-tip);
    let lo=(p[1].x-blankExtension)*(1-u)+(p[0].x-.015)*u;
    let hi=(p[2].x+blankExtension)*(1-u)+(p[3].x+.015)*u;
    const mid=(lo+hi)/2;
    for(const [x,cy]of cutters){const dy=y-cy;if(Math.abs(dy)>=radius)continue;const half=Math.sqrt(radius*radius-dy*dy);if(x<mid)lo=Math.max(lo,x+half);else hi=Math.min(hi,x-half);}
    if(lo>=hi){if(started)throw new Error(`Disconnected tooth ${side}/${index}`);continue;}
    started=true;left.push([lo,y]);right.push([hi,y]);
  }
  if(!started)throw new Error(`Erased tooth ${side}/${index}`);
  const outline=[...simplify(left,.000015),...simplify(right,.000015).reverse()].map(([x,y])=>[+x.toFixed(10),+(y*side).toFixed(10)]);
  result.push({side,index,outline,tipHeight:left[0][1],rootHeight:root,cutters:cutters.length});
}
const data={poses,rows,clearance,blankExtension,pinRadius:g.lanternPinRadius,teeth:result};
const output=`// Generated by scripts/generate-partial-lantern-rack.mjs.\nexport default ${JSON.stringify(data)};\n`;
const file=new URL('../src/simulation/baked/partial-lantern-rack.js',import.meta.url);
if(process.argv.includes('--check'))assert.equal(await readFile(file,'utf8'),output);else await writeFile(file,output);
console.log({vertices:result.reduce((n,t)=>n+t.outline.length,0),tips:result.map(t=>t.tipHeight),bytes:output.length});
