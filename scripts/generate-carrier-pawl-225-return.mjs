// Bake movement 225's tracked pawl return (see vibratingCarrierSinglePawlRatchet):
// from the seated end of the drive the pawl is swung in, step by step, to
// its first resting pose on the wheel outline (nose and the edge behind it),
// falls under a constant bias where the teeth drop away, and runs on past
// the next tip before the drive stroke brings it back down into the root.
// `--check` recomputes the table and fails if the bake differs.
import { readFile, writeFile } from 'node:fs/promises';
import { createAuthoredIntermittentMovement as create } from '../src/simulation/authored-intermittent.js';
globalThis.__bakeLive225 = true;
const bake = create({ id: 225 }).root.userData.returnBake225();
const path = new URL('../src/simulation/baked/carrier-pawl-225-return.js', import.meta.url);
const text = `// Generated by scripts/generate-carrier-pawl-225-return.mjs.\nexport const carrierPawl225Return = ${JSON.stringify(bake)};\n`;
if (process.argv.includes('--check')) {
  if ((await readFile(path, 'utf8')) !== text) { console.error('carrier-pawl-225-return bake is stale'); process.exit(1); }
  console.log(`carrier-pawl-225-return bake current (${bake.angles.length} samples)`);
} else {
  await writeFile(path, text);
  console.log(`wrote ${bake.angles.length} samples`);
}
