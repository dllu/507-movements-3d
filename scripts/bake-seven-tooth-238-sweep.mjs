// Bakes the region swept by movement 238's star wheel D relative to the
// anchor (carrier-local coordinates, pivot A at the origin) over one full
// escapement cycle. The anchor's front layer is its outline minus this
// region, so B and C stand flush in one plate. Offline because the union of
// 600 star poses takes seconds.
import fs from 'node:fs';
import {createHash} from 'node:crypto';
import * as THREE from 'three';
import {createMovementModel} from '../src/simulation/registry.js';
import {polygonClipping as clip, poly} from '../src/simulation/finite-plate-geometry.js';
import data from '../src/simulation/baked/seven-tooth-238-profiles.js';

const catalog = JSON.parse(fs.readFileSync('src/data/movements.json', 'utf8')).movements;
const model = createMovementModel(catalog[237]);
const d = model.root.userData, b = d.blocks, period = d.geometry.cyclePeriod;
// 3% radial growth (0.03 at the tips) leaves running clearance; 3000 poses
// (tip travel between poses at most 0.005) keep the swept edge smooth.
// Drop vertices within the tolerance of the chord of their neighbours (a
// Douglas-Peucker pass); the 0.03 growth margin dwarfs the tolerance.
const simplify = (ring, tolerance) => {
  const keep = new Uint8Array(ring.length); keep[0] = keep[ring.length - 1] = 1;
  const stack = [[0, ring.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop(); let worst = -1, index = -1;
    const [ax, ay] = ring[a], [bx, by] = ring[b], dx = bx - ax, dy = by - ay, length = Math.hypot(dx, dy) || 1e-12;
    for (let i = a + 1; i < b; i++) { const e = Math.abs((ring[i][0] - ax) * dy - (ring[i][1] - ay) * dx) / length; if (e > worst) { worst = e; index = i; } }
    if (worst > tolerance) { keep[index] = 1; stack.push([a, index], [index, b]); }
  }
  return ring.filter((_, i) => keep[i]);
};
const growth = 1.03, poses = 3000, starTolerance = 0.0005;
// The star outline is thinned by the same chord test (tips kept exactly).
const points = [...simplify(data.outline.slice(0, 540), starTolerance), ...simplify([...data.outline.slice(539), data.outline[0]], starTolerance).slice(1, -1)]
  .map(([x, y]) => [x * growth, y * growth]);
const body = b.escapeWheel.userData.body, carrier = b.palletCarrier, rotor = b.escapeWheel.userData.rotor ?? b.escapeWheel;
const polygons = [], v = new THREE.Vector3();
for (let i = 0; i < poses; i++) {
  const s = d.stateAtTime(period * i / poses);
  rotor.rotation.z = s.wheelAngle; carrier.rotation.z = s.palletAngle; model.root.updateMatrixWorld(true);
  const m = carrier.matrixWorld.clone().invert().multiply(body.matrixWorld);
  polygons.push(poly(points.map(([x, y]) => { v.set(x, y, 0).applyMatrix4(m); return [Math.round(v.x * 1e5) / 1e5, Math.round(v.y * 1e5) / 1e5]; })));
}
// Pairwise (tree) union on a 1e-5 grid keeps polygon-clipping robust.
let level = polygons;
while (level.length > 1) {
  const next = [];
  for (let i = 0; i < level.length; i += 2) next.push(i + 1 < level.length ? clip.union(level[i], level[i + 1]) : level[i]);
  level = next;
}
const swept = level[0];
if (swept.length !== 1) throw new Error(`expected one swept region, got ${swept.length}`);
const round = (x) => Math.round(x * 1e5) / 1e5;
const ring = swept[0][0].slice(0, -1);
let far = 0;
ring.forEach((p, i) => { if (Math.hypot(p[0] - ring[0][0], p[1] - ring[0][1]) > Math.hypot(ring[far][0] - ring[0][0], ring[far][1] - ring[0][1])) far = i; });
const outline = [...simplify(ring.slice(0, far + 1), 0.002), ...simplify([...ring.slice(far), ring[0]], 0.002).slice(1, -1)]
  .map(([x, y]) => [round(x), round(y)]);
const hash = (file) => createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const sources = ['scripts/bake-seven-tooth-238-sweep.mjs', 'src/simulation/authored-escapements.js', 'src/simulation/seven-tooth-238-contact.js',
  'src/simulation/baked/seven-tooth-238-profiles.js'].map((file) => ({file, sha256: hash(file)}));
fs.writeFileSync('src/simulation/baked/seven-tooth-238-sweep.js',
  '// Generated by scripts/bake-seven-tooth-238-sweep.mjs. Do not edit.\n'
  + `// Star wheel D's swept region in the anchor's frame over one cycle (${poses} poses, ${growth} radial growth).\n`
  + `export default ${JSON.stringify({poses, growth, starTolerance, starPoints: points.length, sources, outline})};\n`);
console.log({starPoints: points.length, points: outline.length, holes: swept[0].length - 1});
