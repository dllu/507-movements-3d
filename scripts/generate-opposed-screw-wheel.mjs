// Hob the 36-tooth wheel of movement 151 from its own finer worm and write
// src/simulation/opposed-screw-wheel-data.js (one periodic tooth sector).
import fs from 'node:fs';
import {generateSaddleWheel} from '../src/simulation/mujoco-worm-saddle/hob.js';
import {opposedScrewWormProfile} from '../src/simulation/opposed-screw-profile.js';
const f=opposedScrewWormProfile(),options={angularSteps:128,axialSteps:32,phaseSteps:1280,radialSteps:128},start=performance.now();
const {phases,...cut}=generateSaddleWheel(f,options);
const output='src/simulation/opposed-screw-wheel-data.js';
fs.writeFileSync(output,'// Generated by scripts/generate-opposed-screw-wheel.mjs; one periodic hobbed tooth.\nexport const opposedScrewWheelCut = '+JSON.stringify(cut)+';\n');
console.log({output,seconds:(performance.now()-start)/1000,seamError:cut.seamError,minimum:Math.min(...cut.radii),maximum:Math.max(...cut.radii),samples:cut.radii.length});
