import { readFile, writeFile } from 'node:fs/promises';
import { createMovementModel } from '../src/simulation/registry.js';
import { crownToothGeometry } from '../src/simulation/face-gear-geometry.js';
import { spiralWheelGeometry } from '../src/simulation/spiral-wheel-geometry.js';
import { wormWheelGeometry } from '../src/simulation/worm-gear-geometry.js';
import { steppedSectorCut } from '../src/simulation/stepped-sector-geometry.js';
import { mangleToothOutline } from '../src/simulation/mangle-gear-geometry.js';

// Retain the generating code and its complete input keys. Parameter changes
// automatically fall back to generation until this script is run again.
const catalog = JSON.parse(await readFile(new URL('../src/data/movements.json', import.meta.url)));
const crown = createMovementModel(catalog.movements[25]).root.userData.blocks.crown;
const spiral = createMovementModel(catalog.movements[28]).root.userData.blocks.gear;
const wormWheel = createMovementModel(catalog.movements[30]).root.userData.blocks.wheel;
const mangleWheel = createMovementModel(catalog.movements[35]).root.userData.blocks.wheel;
const crownKey = crown.userData.faceTeeth[0].geometry.userData.profileKey;
const spiralKey = spiral.userData.toothMesh.geometry.userData.profileKey;
const wormKey = wormWheel.userData.toothMesh.geometry.userData.profileKey;
const mangleKey = mangleWheel.userData.generatedCut.profileKey;
const crownData = crownToothGeometry(JSON.parse(crownKey), { regenerate: true }).userData;
const spiralData = spiralWheelGeometry(JSON.parse(spiralKey), { regenerate: true }).userData;
const wormData = wormWheelGeometry(JSON.parse(wormKey), { regenerate: true }).userData;
const mangleData = mangleToothOutline(JSON.parse(mangleKey), { regenerate: true });
const sectorData = steppedSectorCut(2.8, { regenerate: true });
await writeFile(new URL('../src/data/contact-profiles.js', import.meta.url),
  '// Generated by scripts/bake-contact-profiles.mjs; do not edit the samples by hand.\n'
  + `export const crownCut = ${JSON.stringify({ key: crownKey, heights: crownData.heights })};\n`
  + `export const spiralCut = ${JSON.stringify({ key: spiralKey, radii: spiralData.radii })};\n`
  + `export const wormCut = ${JSON.stringify({ key: wormKey, id: wormData.profileId,
    angularSteps: wormData.angularSteps, axialSteps: wormData.axialSteps,
    phaseSteps: wormData.phaseSteps, radialSteps: wormData.radialSteps,
    clearance: wormData.clearance, radii: wormData.radii })};\n`
  + `export const mangleCut = ${JSON.stringify({ key: mangleKey, heights: mangleData.heights })};\n`
  + `export const steppedSectorCut = ${JSON.stringify({ key: sectorData.profileKey, radii: sectorData.radii })};\n`);
console.log('Saved crown, spiral, worm, mangle and stepped-sector cutting profiles.');
