import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { makeMutilatedBevelRuntimeCandidate } from './lib/mutilated-bevel-runtime-candidate.mjs';

const bakeFile = 'artifacts/review/074-contact-spline-bake.json';
const bake = JSON.parse(await readFile(bakeFile, 'utf8'));
const relief = JSON.parse(await readFile(bake.relief, 'utf8'));
const model = makeMutilatedBevelRuntimeCandidate(bake, relief);
const relievedTeeth = model.root.userData.blocks.driverC.userData.toothMeshes
  .filter(mesh => mesh.geometry.userData.profile === 'relieved-back-cone-involute')
  .map(mesh => ({
    index: mesh.userData.index,
    positions: Array.from(mesh.geometry.attributes.position.array),
    normals: Array.from(mesh.geometry.attributes.normal.array),
    metadata: mesh.geometry.userData,
  }));
const provenance = [];
for (const file of [bakeFile, bake.relief, bake.motionFile,
  'scripts/lib/mutilated-bevel-candidate.mjs', 'scripts/lib/mutilated-bevel-tooth-relief.mjs',
  'scripts/lib/mutilated-bevel-contact-spline.mjs']) {
  provenance.push({ file, sha256: createHash('sha256').update(await readFile(file)).digest('hex') });
}
const profile = { parameters: bake.parameters, motion: bake.profile, relievedTeeth, provenance };
// JavaScript preserves signed zero; JSON alone would lose it in the analytic
// cap normals. Keep every exported Float32 buffer byte-identical to the audit.
const literal = JSON.stringify(profile, (_, value) => Object.is(value, -0) ? '__NEGATIVE_ZERO__' : value)
  .replaceAll('"__NEGATIVE_ZERO__"', '-0');
await writeFile('src/data/mutilated-bevel-profile.js',
  '// Generated by scripts/export-mutilated-bevel-profile.mjs. See artifacts/review/074-reconstruction-notes.md.\n'
  + '// Contact knots and four relieved tooth skins are baked offline; playback performs no Boolean cuts or contact search.\n'
  + `export default ${literal};\n`);
console.log({ knots: profile.motion.nodes.length, relievedTeeth: relievedTeeth.length,
  vertices: relievedTeeth.reduce((sum, tooth) => sum + tooth.positions.length / 3, 0) });
