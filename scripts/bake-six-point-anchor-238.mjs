// Bakes movement 238's wheel motion: the anchor swings sinusoidally and the
// urged star wheel stops wherever it first meets the anchor (with recoil when
// a pallet enters a root). Offline because the polygon contact search over
// three cycles takes a few seconds.
//   node scripts/bake-six-point-anchor-238.mjs [--check]
import fs from 'node:fs';
import {createHash} from 'node:crypto';
import {DESIGN, simulateWheel} from '../src/simulation/six-point-anchor-238.js';

const out = 'src/simulation/baked/six-point-anchor-238-wheel.js';
const steps = 1200;
const result = simulateWheel(steps);
const closureError = result.closure - 2 * Math.PI / DESIGN.teeth;
if (Math.abs(closureError) > 1e-6) throw new Error(`238 cycle does not close: ${closureError}`);
const sha256 = createHash('sha256').update(fs.readFileSync('src/simulation/six-point-anchor-238.js')).digest('hex');
const table = result.table.map(x => Math.round(x * 1e7) / 1e7);
const text = '// Generated by scripts/bake-six-point-anchor-238.mjs. Do not edit.\n'
  + '// One anchor cycle of star wheel D\'s angle (radians from the plate pose), phase i/steps.\n'
  + `export default ${JSON.stringify({steps, closure: Math.round(result.closure * 1e9) / 1e9, source: {file: 'src/simulation/six-point-anchor-238.js', sha256}, table})};\n`;
if (process.argv.includes('--check')) {
  if (fs.readFileSync(out, 'utf8') !== text) { console.error(`${out} is stale`); process.exit(1); }
  console.log('up to date');
} else { fs.writeFileSync(out, text); console.log({steps, closureError}); }
