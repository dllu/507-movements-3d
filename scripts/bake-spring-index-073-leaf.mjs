#!/usr/bin/env node
// Bakes movement 73's planar contact pass (strong spring C's four bending
// modes, B's nib offset and A's angle) from
// src/simulation/spring-index-073-leaf.js. The factory falls back to the
// live simulation whenever the fingerprint no longer matches.
import { readFile, writeFile } from 'node:fs/promises';
import { createMovementModel } from '../src/simulation/registry.js';
import { simulateSpringIndex073, springIndex073Fingerprint } from '../src/simulation/spring-index-073-leaf.js';

const output = new URL('../src/simulation/baked/spring-index-073-leaf.js', import.meta.url);
const catalog = JSON.parse(await readFile(new URL('../src/data/movements.json', import.meta.url), 'utf8'));
const started = performance.now();
const config = createMovementModel(catalog.movements.find(({ id }) => id === 73)).root.userData.simulationConfig;
const result = simulateSpringIndex073(config);
const round = (value) => Math.round(value * 1e8) / 1e8;
const body = JSON.stringify({
  fingerprint: springIndex073Fingerprint(config),
  samples: result.samples,
  record: result.record,
  sampleDt: result.sampleDt,
  duration: result.duration,
  dof: result.dof,
  modes: result.modes,
  nibIndex: result.nibIndex,
  wheelIndex: result.wheelIndex,
  rest: result.rest.map(round),
  restSpeed: result.restSpeed,
  residual: result.residual.map(round),
  flags: Array.from(result.flags).join(''),
  states: Array.from(result.states, round),
});
await writeFile(output, `// Generated by scripts/bake-spring-index-073-leaf.mjs.\nexport default ${body};\n`);
console.log(JSON.stringify({
  fingerprint: springIndex073Fingerprint(config),
  milliseconds: Math.round(performance.now() - started),
  residual: result.residual,
  samples: result.samples,
}));
