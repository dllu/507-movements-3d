import fs from 'node:fs';
import {createAuthoredExpandingPulleyMovement} from '../src/simulation/authored-expanding-pulleys.js';
import {disposeObject3D} from '../src/simulation/dispose-model.js';

// Bake movement 224's click-e resting angle over one pinion tooth pitch: the
// click falls toward pinion d until it touches d's finite teeth.
const catalog = JSON.parse(fs.readFileSync('src/data/movements.json', 'utf8')).movements;
const model = createAuthoredExpandingPulleyMovement(catalog[223]);
try {
  const table = model.root.userData.computeClickRestTable().map((value) => +value.toFixed(7));
  fs.writeFileSync('src/simulation/generated-expanding-pulley-click.js',
    '// Generated by scripts/generate-expanding-pulley-click.mjs; click e rest angle over one pitch of d.\n'
      + `export default ${JSON.stringify(table)};\n`);
  console.log({samples: table.length});
} finally {disposeObject3D(model.root);}
