// p108: lowers 081's rest, and so its whole settled stroke, by exactly one
// rack pitch, so the segment's first tooth takes the rack's top tooth (the
// user's review: the top tooth was never engaged). A whole-pitch translation
// maps the reviewed finite-contact solution onto itself: tooth k+1's contacts
// become tooth k's, and the spring force depends only on the lift above rest.
// The contact-study inputs (artifacts/review) are not tracked, so this script
// transforms the committed integrated profile in place. It is idempotent: the
// recorded restDrop is undone before the new drop is applied.
import fs from 'node:fs';
import * as THREE from 'three';
import profileModule from '../src/data/spring-rack-profile.js';
import measured from '../src/data/spring-rack-source.js';
import {makeSpringRackGeometry} from '../src/simulation/spring-rack-geometry.js';
import {makeSpringRackCoil} from '../src/simulation/spring-rack-coil.js';

const file='src/data/spring-rack-profile.js',header='// Generated by scripts/integrate-spring-rack.mjs from the reviewed contact study; rest lowered by scripts/lower-spring-rack-rest.mjs.';
const profile=structuredClone(profileModule),previous=profile.restDrop?.world??0,
 restDropPixels=measured.pitch,lowerGuideDropPixels=35,drop=restDropPixels/measured.scale,shift=previous-drop;
const move=y=>y+shift;
profile.knots=profile.knots.map(([t,y])=>[t,move(y)]);
profile.range=profile.range.map(move);
profile.parameters={...profile.parameters,stop:move(profile.parameters.stop),upper:move(profile.parameters.upper)};
profile.geometry={...profile.geometry,restDropPixels,lowerGuideDropPixels};
profile.restDrop={world:drop,pixels:restDropPixels,teeth:1,
 note:'Rest and settled stroke lowered by one rack pitch (p108) so the first segment tooth drives the top rack tooth; knots, range, stop and upper are the reviewed solution translated by -world.'};

const model=makeSpringRackGeometry(profile.geometry),u=model.root.userData,p=u.geometry,bounds=new THREE.Box3(),
 coil=makeSpringRackCoil({...p.spring,referenceSpan:p.spring.top-p.spring.bottom-2*p.spring.wireRadius}),
 outer=coil.radiusAt(p.spring.top-p.spring.bottom-2*p.spring.wireRadius-profile.range[1])+p.spring.wireRadius;
// Same envelope construction as scripts/integrate-spring-rack.mjs.
for(const [name,mesh] of Object.entries(u.parts)){
 const box=new THREE.Box3().setFromObject(mesh),family=u.families[name];
 if(family==='gear'){
  const position=mesh.geometry.attributes.position;let R=0;
  for(let i=0;i<position.count;i++)R=Math.max(R,Math.hypot(position.getX(i),position.getY(i)));
  box.min.x=box.min.y=-R;box.max.x=box.max.y=R;
 }else if(family==='rack'){box.min.y+=profile.range[0];box.max.y+=profile.range[1];}
 else if(family==='spring'){
  box.min.set(p.spring.axisX-outer,p.spring.bottom+profile.range[0],p.spring.axisZ-outer);
  box.max.set(p.spring.axisX+outer,p.spring.top,p.spring.axisZ+outer);
 }
 bounds.union(box);
}
bounds.expandByScalar(2e-6);
profile.motionBounds={min:bounds.min.toArray(),max:bounds.max.toArray()};
fs.writeFileSync(file,header+'\nexport default '+JSON.stringify(profile)+';\n');
console.log({drop,range:profile.range,stop:profile.parameters.stop,motionBounds:profile.motionBounds});
