import {writeFile} from 'node:fs/promises';
const R=1.52,pitch=Math.PI/4,half=pitch*.36,gap=1.10,centerRadius=1.04,rollerRadius=.125,rollerLength=.35;
const height=2*(gap*Math.tan(half)+.035),angular=96,vertical=64,clearance=.002,states=[];
for(let i=0;i<=384;i++){
 const phi=-pitch/2+pitch*i/384,u=Math.max(0,Math.min(1,(Math.tan(phi)+Math.tan(half))/(2*Math.tan(half)))),f=u*u*u*(10-15*u+6*u*u),a=f*pitch;
 const cp=Math.cos(phi),sp=Math.sin(phi),ca=Math.cos(a),sa=Math.sin(a),x=-R-gap+centerRadius*cp;
 states.push({c:[x*ca,centerRadius*sp,-x*sa],v:[cp*ca,sp,-cp*sa]});
}
function radiusAt(delta,y){
 let radius=R;
 for(const copy of[-1,0,1]){
  const angle=Math.PI-delta+copy*pitch,ex=Math.cos(angle),ez=Math.sin(angle);
  for(const{c,v}of states){
   const dx=c[0],dy=c[1]-y,dz=c[2],ev=ex*v[0]+ez*v[2],dv=dx*v[0]+dy*v[1]+dz*v[2];
   const A=1-ev*ev,B=-2*(ex*dx+ez*dz-ev*dv),C=dx*dx+dy*dy+dz*dz-dv*dv-(rollerRadius+clearance)**2,disc=B*B-4*A*C;
   if(disc<0||A<1e-12)continue;
   let lo=(-B-Math.sqrt(disc))/(2*A),hi=(-B+Math.sqrt(disc))/(2*A);
   if(Math.abs(ev)>1e-12){const a=(dv-rollerLength/2-clearance)/ev,b=(dv+rollerLength/2+clearance)/ev;lo=Math.max(lo,Math.min(a,b));hi=Math.min(hi,Math.max(a,b));}
   else if(Math.abs(dv)>rollerLength/2+clearance)continue;
   if(hi>=lo&&hi>=0&&lo<R)radius=Math.min(radius,Math.max(0,lo));
  }
 }
 return radius;
}
const values=[],angles=[],insideCount=64,outsideCount=16;
for(let j=0;j<=vertical;j++){
 const y=-height/2+height*j/vertical,u=Math.max(0,Math.min(1,(y/gap+Math.tan(half))/(2*Math.tan(half)))),center=u*u*u*(10-15*u+6*u*u)*pitch;
 const probes=Array.from({length:129},(_,i)=>({a:center-pitch/2+pitch*i/128,r:radiusAt(center-pitch/2+pitch*i/128,y)}));
 const first=probes.findIndex(p=>p.r<R-1e-8),last=probes.findLastIndex(p=>p.r<R-1e-8);
 if(first<1||last>=128)throw new Error('Groove interval is not isolated');
 let leftOutside=probes[first-1].a,leftInside=probes[first].a,rightInside=probes[last].a,rightOutside=probes[last+1].a;
 for(let k=0;k<30;k++){
  let mid=(leftOutside+leftInside)/2;if(radiusAt(mid,y)<R-1e-8)leftInside=mid;else leftOutside=mid;
  mid=(rightInside+rightOutside)/2;if(radiusAt(mid,y)<R-1e-8)rightInside=mid;else rightOutside=mid;
 }
 // Duplicate mouth angles with their two finite radii: interpolation must not
 // bridge from the bottom of a groove across its open mouth.
 const row=[{a:leftOutside-1e-7,r:R},{a:leftInside+1e-7,r:radiusAt(leftInside+1e-7,y)}];
 for(let i=1;i<insideCount;i++){const a=leftInside+(rightInside-leftInside)*i/insideCount;row.push({a,r:radiusAt(a,y)});}
 row.push({a:rightInside-1e-7,r:radiusAt(rightInside-1e-7,y)},{a:rightOutside+1e-7,r:R});
 for(let i=1;i<outsideCount;i++)row.push({a:rightOutside+(leftOutside+pitch-rightOutside)*i/outsideCount,r:R});
 for(const p of row){angles.push(Math.round(p.a*1e8)/1e8);values.push(Math.round(p.r*1e8)/1e8);}
}
const rowCount=values.length/(vertical+1);
const data={radius:R,pitch,angular:rowCount,vertical,height,clearance,angles,values};
await writeFile(new URL('../src/simulation/baked/roller-indexer-grooves.js',import.meta.url),`// Generated by scripts/generate-roller-indexer-grooves.mjs.\nexport default ${JSON.stringify(data)};\n`);
console.log({height,min:Math.min(...values),max:Math.max(...values),vertices:values.length,states:states.length});
