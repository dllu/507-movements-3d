import{readFile,writeFile}from'node:fs/promises';
import{createHash}from'node:crypto';
import{makeTiltHammerCandidate}from'./lib/tilt-hammer-candidate.mjs';
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
const checkpoint=JSON.parse(await readFile('artifacts/review/072-candidate-checkpoint.json','utf8'));
for(const[file,expected]of Object.entries(checkpoint.sources))if(hash(await readFile(file))!==expected)
  throw new Error('Audited candidate source changed: '+file);
const model=makeTiltHammerCandidate(),{parts,families,motion}=model.root.userData;
const lowByName={hammerBody:-.14,hammerSleeve:-.14,striker:-.14,camBody:-.1,workpiece:-.2,anvil:-.32,
  foundation:-.5,socketLiner:-.15,pivotRearSupport:-.5,camRearPost:-.46};
const descriptors=Object.entries(parts).map(([name,mesh])=>{
  const geometry=mesh.geometry;
  const expected=checkpoint.meshes.find(item=>item.name===name);
  for(const[key,attribute]of Object.entries(geometry.attributes)){
    if(hash(Buffer.from(attribute.array.buffer,attribute.array.byteOffset,attribute.array.byteLength))!==expected.attributes[key])
      throw new Error('Candidate geometry changed: '+name+'/'+key);
  }
  let shape;
  if(name==='camBody')shape={kind:'cam',segments:2048,low:-.1,depth:.2};
  else if(geometry.userData.profile)shape={kind:'turned',...geometry.userData};
  else{
    const shapes=Array.isArray(geometry.parameters.shapes)?geometry.parameters.shapes:[geometry.parameters.shapes];
    shape={kind:'plate',low:lowByName[name],depth:geometry.parameters.options.depth,
      polygons:shapes.map(shape=>[shape.getPoints().map(p=>p.toArray()),...shape.holes.map(hole=>hole.getPoints().map(p=>p.toArray()))])};
    if(!Number.isFinite(shape.low))throw new Error('Unknown plate translation '+name);
  }
  return{name,family:families[name],shape,position:mesh.position.toArray(),color:mesh.material.color.toArray()};
});
const profile={parameters:{...motion.parameters,initialTime:motion.parameters.inputStart/motion.parameters.omega},
  mass:{...motion.mass,contours:undefined},events:motion.events,fall:motion.fall.map(row=>[row.time,row.q,row.velocity]),parts:descriptors};
const file='src/data/tilt-hammer-profile.js';
await writeFile(file,'// Generated by scripts/export-tilt-hammer-runtime.mjs from the audited 072 candidate.\nexport default '+JSON.stringify(profile)+';\n',{flag:'wx'});
await writeFile('artifacts/review/072-runtime-export.json',JSON.stringify({movement:72,file,sha256:hash(await readFile(file)),
  candidateSources:checkpoint.sources,parts:descriptors.length,fallKnots:profile.fall.length,
  qualification:'The export preserves source contours, Float32-audited geometry construction, event times and the converged gravity trajectory. Runtime mesh and state equivalence must still be checked.'},null,2)+'\n',{flag:'wx'});
console.log({file,parts:descriptors.length,fallKnots:profile.fall.length,bytes:(await readFile(file)).length});
