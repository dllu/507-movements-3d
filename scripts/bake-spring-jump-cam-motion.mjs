import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { makeJumpCamMotion } from '../src/simulation/spring-jump-cam-motion.js';

const start = Date.now(), motion = makeJumpCamMotion(), hashes = {};
for (const name of ['spring-jump-cam-contact.js', 'spring-jump-cam-motion.js']) {
  hashes[name] = createHash('sha256').update(await readFile(`src/simulation/${name}`)).digest('hex');
}
const data = { sourceHashes: hashes, parameters: motion.parameters, integration: motion.integration,
  table: motion.table.flatMap(row => [row.lambda, row.lambdaDerivative, row.followerAngle, row.rollerRatio, row.rollerAngle]),
  frames: motion.frames.flatMap(row => [row.time, row.angle, row.speed]) };
const text = `// Generated by scripts/bake-spring-jump-cam-motion.mjs.\nexport default ${JSON.stringify(data)};\n`;
await writeFile('src/data/spring-jump-cam-motion.js', text);
console.log({ seconds: (Date.now() - start) / 1000, bytes: text.length, frames: motion.frames.length, samples: motion.table.length, hashes });
