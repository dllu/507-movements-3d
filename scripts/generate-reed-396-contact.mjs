import {readFileSync,writeFileSync} from 'node:fs';
import {reed396,reed396Profiles,reed396Pose,reed396Obstacles,reed396Contact} from '../src/simulation/reed-396-contact.js';
const profile=reed396Profiles(),count=4096,dt=reed396.period/count;
// The cycle starts at the clockwise extreme with the wheel resting on g's
// locking arc: find that rest angle from the nominal lock point.
const restAngle=(()=>{const obstacles=reed396Obstacles(reed396Pose(0),profile.pallets),gap=a=>reed396Contact(a,obstacles,profile.teeth).gap;
 let hi=reed396.gAngle+.5*Math.PI/180;if(gap(hi)<0)throw new Error('Rest search starts blocked');let lo=hi;while(gap(lo)>=0)lo-=.001;
 for(let k=0;k<60;k++){const mid=(lo+hi)/2;if(gap(mid)<0)lo=mid;else hi=mid;}return hi;})();
const knots=[[0,Number(restAngle.toFixed(15)),1]];
function advance(t0,angle,t1,depth=0){
 const obstacles=reed396Obstacles(reed396Pose(t1),profile.pallets),gap=a=>reed396Contact(a,obstacles,profile.teeth).gap;
 if(gap(angle)<-2e-8)throw new Error(`Moving pallet requires recoil at ${t1}: ${gap(angle)}`);
 const limit=angle-reed396.freeDropSpeed*(t1-t0);let last=angle;
 for(let j=1;j<=10;j++){
  const next=angle+(limit-angle)*j/10;
  if(gap(next)<0){let lo=next,hi=last;for(let k=0;k<30;k++){const mid=(lo+hi)/2;if(gap(mid)<0)lo=mid;else hi=mid;}last=hi;break;}
  last=next;
 }
 // Integrate substeps again rather than correcting a chord against stale end
 // positions: a contact-release corner can have a narrow collision interval.
 let bad=false;
 for(const u of[.211,.5,.739]){const t=t0+(t1-t0)*u,w=angle+(last-angle)*u;if(reed396Contact(w,reed396Obstacles(reed396Pose(t),profile.pallets),profile.teeth).gap < -2e-8){bad=true;break;}}
 if(bad){if(depth>=20)throw new Error(`Adaptive interpolation failed at ${t0}`);const t=(t0+t1)/2;advance(t0,angle,t,depth+1);advance(t,knots.at(-1)[1],t1,depth+1);return;}
 const c=reed396Contact(last,obstacles,profile.teeth);knots.push([t1,Number(last.toFixed(15)),c.gap<1e-7?c.pallet+1:0]);
}
for(let i=0;i<count;i++)advance(i*dt,knots.at(-1)[1],(i+1)*dt);
const advanceAngle=knots.at(-1)[1]-knots[0][1];if(Math.abs(advanceAngle+reed396.pitch)>1e-8)throw new Error('Cycle did not advance one tooth');
// Close the cycle exactly: the last knot is the first one tooth later.
knots.at(-1)[1]=Number((knots[0][1]-reed396.pitch).toFixed(15));
const target=new URL('../src/simulation/baked/reed-396-contact.js',import.meta.url),text=`// Generated by node scripts/generate-reed-396-contact.mjs\nexport const reed396ContactBake = ${JSON.stringify({period:4,times:knots.map(q=>q[0]),samples:knots.map(q=>q.slice(1))})};\n`;
if(process.argv.includes('--check')){if(readFileSync(target,'utf8')!==text)throw new Error('Reed 396 bake differs; regenerate');}else writeFileSync(target,text);
console.log({samples:knots.length,adaptive:knots.length-count-1,advance:advanceAngle,restAngle,check:process.argv.includes('--check')});
