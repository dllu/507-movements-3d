#!/usr/bin/env node
// Bakes movement 63's swept pawl and relieved drop outlines.
import { readFile, writeFile } from 'node:fs/promises';
import { createMovementModel } from '../src/simulation/registry.js';
import { computeSnapCounterCuts } from './lib/intermittent-63-211-snap-counter-cuts.mjs';

const output = new URL('../src/simulation/baked/intermittent-63-211-snap-counter-cuts.js', import.meta.url);
const catalog = JSON.parse(await readFile(new URL('../src/data/movements.json', import.meta.url), 'utf8'));
const model = createMovementModel(catalog.movements.find((movement) => movement.id === 63));
const { fingerprint, inputs } = model.root.userData.sweptCut;
const started = performance.now();
const cuts = computeSnapCounterCuts(inputs, model.root.userData.stateAtTime);
const body = JSON.stringify({ fingerprint, pawl: cuts.pawl, pawlNose: cuts.pawlNose, dropRear: cuts.dropRear });
await writeFile(output, `// Generated by scripts/bake-intermittent-63-211-snap-counter.mjs.\nexport default ${body};\n`);
console.log(JSON.stringify({
  dropRearPieces: cuts.dropRear.length,
  dropRelativeAngleRange: cuts.dropRelativeAngleRange,
  fingerprint,
  milliseconds: Math.round(performance.now() - started),
  noseArea: cuts.pawlNose.length,
  pawlPieces: cuts.pawl.length,
  pawlSamples: cuts.pawlSampleCount,
}));
