#!/usr/bin/env node
// Bakes movement 63's steady planar contact motion (drop, pawl and star
// angles for one pin event) from src/simulation/snap-counter-63-mechanism.js.
import { writeFile } from 'node:fs/promises';
import {
  makeSnapCounterMechanism,
  snapCounterMotionFingerprint,
} from '../src/simulation/snap-counter-63-mechanism.js';

const output = new URL('../src/simulation/baked/intermittent-63-211-snap-counter-cuts.js', import.meta.url);
const started = performance.now();
const mechanism = makeSnapCounterMechanism();
const event = mechanism.periodicEvent();
const round = (value) => Math.round(value * 1e7) / 1e7;
const body = JSON.stringify({
  fingerprint: snapCounterMotionFingerprint(),
  stepsPerEvent: event.stepsPerEvent,
  startSigma: round(event.startSigma),
  phaseOffset: round(event.phaseOffset),
  advance: round(event.advance),
  repeatError: round(event.repeatError),
  delta: event.delta.map(round),
  rho: event.rho.map(round),
  sigma: event.sigma.map(round),
});
await writeFile(output, `// Generated by scripts/bake-intermittent-63-211-snap-counter.mjs.\nexport default ${body};\n`);
console.log(JSON.stringify({
  advanceDegrees: event.advance * 180 / Math.PI,
  fingerprint: snapCounterMotionFingerprint(),
  maxDropDegrees: Math.max(...event.delta) * 180 / Math.PI,
  milliseconds: Math.round(performance.now() - started),
  repeatError: event.repeatError,
}));
