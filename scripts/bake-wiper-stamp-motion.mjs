// Rebakes movement 85's stamp trajectory against the production wiper
// profile (src/simulation/wiper-stamp-geometry.js). The stamp is a rigid
// guided body under gravity: the constant-speed cam lifts projection B
// through unilateral inelastic contact (the support envelope of the actual
// finite cap boundary), releases it when the wiper falls away faster than
// gravity, and the rigid bed stops it inelastically. Knots are the fewest
// that reproduce the fine solution within 1e-6 units by linear interpolation.
// Usage: node scripts/bake-wiper-stamp-motion.mjs [--check]
import fs from 'node:fs';
import assert from 'node:assert/strict';
import profile from '../src/data/wiper-stamp-profile.js';
import {makeWiperStampGeometry} from '../src/simulation/wiper-stamp-geometry.js';
import {makeWiperStampContact} from '../src/simulation/wiper-stamp-contact.js';

const g = 9.81, dt = 2e-5, tolerance = 1e-6, model = makeWiperStampGeometry(), contact = makeWiperStampContact(model);
const minimumY = model.root.userData.geometry.minimumStampY, {angularSpeed, end} = profile;
const support = t => contact.support(angularSpeed * t)?.height ?? -Infinity;
const steps = Math.round(end / dt), ys = new Float64Array(steps + 1);
let y = 0, v = 0;
for (let i = 1; i <= steps; i++) {
  const t = i * dt, s = support(t);
  let yNext = y + v * dt - g * dt * dt / 2, vNext = v - g * dt;
  if (yNext <= s) {vNext = (s - y) / dt; yNext = s;}
  if (yNext <= minimumY) {yNext = minimumY; vNext = 0;}
  y = yNext; v = vNext; ys[i] = y;
}
// Greedy knot reduction: extend each segment while every fine sample stays within tolerance.
const knots = [[0, ys[0]]];
let start = 0;
while (start < steps) {
  let best = start + 1;
  for (let j = start + 2; j <= steps; j++) {
    let ok = true;
    for (let k = start + 1; k < j && ok; k++) ok = Math.abs(ys[start] + (ys[j] - ys[start]) * (k - start) / (j - start) - ys[k]) <= tolerance;
    if (!ok) break; best = j;
    if (j - start > 20000) break;
  }
  knots.push([+(best * dt).toFixed(10), ys[best]]); start = best;
}
const at = t => ys[Math.round(t / dt)], period = profile.period;
for (const t of [1, 1.5, 2.5, 3, 4.9]) assert(Math.abs(at(t) - at(t + (t + period <= end ? period : -period))) < 1e-9 || t + period > end);
assert.equal(at(profile.loopStart), minimumY); assert.equal(at(end), minimumY);
const peak = ys.reduce((a, b) => Math.max(a, b), -Infinity), out = {...profile, knots, range: [minimumY, Math.max(profile.range[1], peak)],
  qualification: 'Symmetric two-wiper rebake: gravity, unilateral inelastic cam contact on the production cap boundary and an inelastic rigid bed.'};
console.log({knots: knots.length, peak, peakPixels: (peak - minimumY) * profile.scale});
assert(peak < profile.motionBounds.max[1]);
const text = '// Generated by scripts/bake-wiper-stamp-motion.mjs (symmetric wipers; originally scripts/integrate-wiper-stamp.mjs).\nexport default ' + JSON.stringify(out) + ';\n';
if (process.argv.includes('--check')) assert.equal(fs.readFileSync('src/data/wiper-stamp-profile.js', 'utf8'), text, 'profile is stale');
else fs.writeFileSync('src/data/wiper-stamp-profile.js', text);
