// Packs the Blender-modelled figure meshes (scripts/blender/figures.py writes
// one JSON file per part) into src/simulation/baked/figure-meshes.js:
// positions quantized to int16 over each part's bounds and a uint16 index,
// both base64, decoded synchronously by src/simulation/figure-meshes.js.
//   node scripts/generate-figure-meshes.mjs <dir-with-part-json>
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = process.argv[2];
if (!dir) throw new Error('usage: node scripts/generate-figure-meshes.mjs <mesh-json-dir>');
const parts = {};
for (const file of readdirSync(dir).filter((name) => name.endsWith('.json')).sort()) {
  const name = file.replace(/\.json$/, '');
  const { positions, triangles, ...extra } = JSON.parse(readFileSync(join(dir, file), 'utf8'));
  if (positions.length > 65535) throw new Error(`${name}: too many vertices`);
  const min = [0, 1, 2].map((axis) => Math.min(...positions.map((p) => p[axis])));
  const max = [0, 1, 2].map((axis) => Math.max(...positions.map((p) => p[axis])));
  const quantized = new Int16Array(positions.length * 3);
  positions.forEach((point, index) => point.forEach((value, axis) => {
    const span = max[axis] - min[axis] || 1;
    quantized[index * 3 + axis] = Math.round(((value - min[axis]) / span) * 65534 - 32767);
  }));
  const index = new Uint16Array(triangles.flat());
  parts[name] = {
    min: min.map((value) => +value.toFixed(6)),
    max: max.map((value) => +value.toFixed(6)),
    position: Buffer.from(quantized.buffer).toString('base64'),
    index: Buffer.from(index.buffer).toString('base64'),
    ...extra,
  };
}
const header = '// Generated by scripts/generate-figure-meshes.mjs from scripts/blender/figures.py.\n';
writeFileSync(new URL('../src/simulation/baked/figure-meshes.js', import.meta.url),
  `${header}export const figureMeshes = ${JSON.stringify(parts)};\n`);
console.log(Object.fromEntries(Object.entries(parts).map(([name, part]) => [name, part.position.length * 3 / 4 / 6])));
