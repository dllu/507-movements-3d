import fs from 'node:fs';
import assert from 'node:assert/strict';
import {readStudyReport,hashStudyFile,freezeStudySources} from './lib/study-report-io.mjs';

const input='artifacts/review/088-gravity-fine.json.gz',r=readStudyReport(input),
  checkFile='artifacts/review/088-reconstruction-check.json',check=readStudyReport(checkFile),tolerance=2e-8;
assert(check.checksPassed&&!r.error&&Math.abs(r.closure.outputError)<1e-10);
const startIndex=Math.round(.4*r.parameters.stepsPerTurn),endIndex=startIndex+2*r.parameters.stepsPerTurn,rows=r.rows.slice(0,endIndex+1),
  events=r.events.filter(e=>e.time<=rows.at(-1).time),keep=new Set([0,startIndex,endIndex]);
for(const e of events){const i=Math.round(e.time/r.parameters.h);for(const k of [i-1,i,i+1])if(k>=0&&k<=endIndex)keep.add(k);}
const split=[...keep].sort((a,b)=>a-b),stack=split.slice(1).map((b,i)=>[split[i],b]);
while(stack.length){
  const [lo,hi]=stack.pop(),a=rows[lo],b=rows[hi];let worst=-1,error=tolerance;
  for(let i=lo+1;i<hi;i++){const f=(rows[i].time-a.time)/(b.time-a.time),d=Math.abs(a.output+f*(b.output-a.output)-rows[i].output);
    if(d>error){worst=i;error=d;}}
  if(worst>=0){keep.add(worst);stack.push([lo,worst],[worst,hi]);}
}
const indices=[...keep].sort((a,b)=>a-b),samples=indices.map(i=>[rows[i].time,rows[i].output]);let maximumError=0,interval=0;
for(const row of rows){while(interval<samples.length-2&&samples[interval+1][0]<row.time)interval++;
  const a=samples[interval],b=samples[interval+1],f=(row.time-a[0])/(b[0]-a[0]);maximumError=Math.max(maximumError,Math.abs(a[1]+f*(b[1]-a[1])-row.output));}
assert(maximumError<=tolerance);
const profile={movement:88,options:r.options,omega:r.parameters.omega,displayPeriod:8,
  repeat:{start:rows[startIndex].time,end:rows[endIndex].time,period:r.closure.period,outputDelta:-2*Math.PI,endpointReplaced:false},samples,events,
  physics:{...r.parameters,stepsPerTurn:undefined,h:undefined,turns:undefined},
  reduction:{originalStates:rows.length,retainedStates:samples.length,tolerance,maximumError},
  provenance:{input,sha256:hashStudyFile(input),check:checkFile,checkSha256:hashStudyFile(checkFile),
    qualification:'Native-contact integration with gravity, dry bearing friction and inelastic drive impacts. Startup is retained; a settled two-index period repeats with continuous input and accumulated output rotation. Hidden output-axis and stepped-foot construction remain reconstruction assumptions.'}};
const output='src/data/eccentric-two-stop-profile.js';
fs.writeFileSync(output,'// Generated by scripts/export-eccentric-two-stop-playback.mjs.\nexport default {'+
  '\n'+Object.entries(profile).map(([key,value])=>JSON.stringify(key)+':'+(key==='samples'?'[\n'+value.map(v=>JSON.stringify(v)).join(',\n')+'\n]':JSON.stringify(value))).join(',\n')+'\n};\n');
const prefix='artifacts/review/088-production-export',sources=freezeStudySources([input,checkFile,output,'scripts/export-eccentric-two-stop-playback.mjs'],prefix);
fs.writeFileSync(prefix+'.json',JSON.stringify({movement:88,sources,profile:{...profile,samples:profile.samples.length},passed:true},null,2)+'\n',{flag:'wx'});
console.log({samples:samples.length,bytes:fs.statSync(output).size,maximumError,repeat:profile.repeat});
